"""Как стройка распределяется по месяцам — одна кривая на движок и на рынок.

Профиль сверен с книгой ПЛАТО (лист CF_x, строка 12): первые 20 % срока идут с
весом 0,6, середина — 1,2, последние 20 % — 0,8, нормируется на сумму весов.
Равномерный разнос расходился с книгой на 2–3 % по процентам ПФ: деньги те же,
помесячный профиль другой.

Модуль общий, потому что этой же кривой отвечают на второй вопрос — какая у
дома готовность в такой-то месяц. Он возникает в отчёте о рынке: цену соседа
надо привести к стадии, а стадия в процентах ниоткуда не приходит — приходят
даты. «Сколько построено к этому месяцу» между двумя датами говорит вот эта
кривая, и другой у проекта быть не должно: две кривые об одном процессе — это
два мнения, которые не с чем сверить.

Чего здесь нет: зависимости цены от готовности. Это другое явление, и лежит
оно в `market_search/stage.py`. Освоение отвечает, сколько работ уложено к
месяцу; цена — сколько покупатель платит за снятый риск, а риск снимается не
пропорционально бетону: самый большой скачок — уход с котлована, когда есть
разрешение и открыт эскроу, а последние проценты отделки цену почти не двигают.
Приравнять их значило бы сказать, что в первые 20 % срока цена растёт медленно,
— на рынке ровно наоборот.
"""

from __future__ import annotations

# Границы и веса профиля. Меняются здесь и больше нигде: копию негде обновлять,
# потому что копии нет.
_EARLY_SHARE = 0.2
_LATE_SHARE = 0.8
_EARLY_WEIGHT = 0.6
_MIDDLE_WEIGHT = 1.2
_LATE_WEIGHT = 0.8


def monthly_weights(months: int) -> list[float]:
    """Вес каждого месяца стройки. Ненормированные — как в книге."""
    months = max(1, int(months))
    return [
        _EARLY_WEIGHT if (index + 1) / months <= _EARLY_SHARE
        else (_MIDDLE_WEIGHT if (index + 1) / months <= _LATE_SHARE else _LATE_WEIGHT)
        for index in range(months)
    ]


def monthly_shares(months: int) -> list[float]:
    """Доля стройки, приходящаяся на каждый месяц. Сумма — единица."""
    weights = monthly_weights(months)
    total = sum(weights) or 1.0
    return [weight / total for weight in weights]


def readiness(month: float, months: int) -> float:
    """Готовность к концу месяца `month` из `months` (0…1).

    Ноль до начала, единица после сдачи. Внутри — накопленная доля освоения,
    то есть та же кривая, которой движок разносит СМР.
    """
    months = max(1, int(months))
    if month <= 0:
        return 0.0
    if month >= months:
        return 1.0
    shares = monthly_shares(months)
    whole = int(month)
    done = sum(shares[:whole])
    # Дробная часть месяца — линейно внутри него: профиль задан помесячно, и
    # притворяться, будто он гладкий внутри месяца, нечем.
    if whole < months:
        done += shares[whole] * (month - whole)
    return min(1.0, done)


def readiness_between(elapsed_months: float, total_months: float) -> float | None:
    """Готовность по сроку: сколько прошло от начала стройки из всего срока.

    `None`, если срок неизвестен или не положителен: нулевая готовность и
    неизвестная — разные вещи, и подставлять первую вместо второй нельзя.
    """
    if not total_months or total_months <= 0:
        return None
    if elapsed_months is None:
        return None
    return readiness(float(elapsed_months), int(round(float(total_months))))
