"""Сверка двух ТЭП одной площадки: что сверено и чем не сошлось.

Пар у нас две, и арифметика у них одна. Первая — «решение ↔ карточка»: город
называет метры и в проекте решения, и в каталоге. Вторая — «карточка ↔ плитка
списка», и она завелась замером 20.09.2026: у «Дербеневской ул. тер. 2» плитка
списка `api.krt.mos.ru/projects/` даёт общий объём 153 320 и ОДН 14 400, а
карточка того же города — 358 100 без ОДН вовсе. Читаем мы плитку и читаем её
верно; расходятся две поверхности источника.

Ответа ТРИ, и свести их к двум нельзя: сверено и сошлось; сверено и
расходится; **сверять не с чем** — величины нет у одной из сторон. Пустой
список расхождений на пустой базе читается как пройденная проверка — та же
ловушка, что у сверки графика платежей за покупку с ценой сделки.

Гектары здесь улика: расходится площадь территории — значит сравнивают разные
площадки, и метрам такой пары верить нельзя. Сверка не чинит расхождение и не
выбирает победителя: она не даёт выдать одно число за другое.
"""

from __future__ import annotations

from typing import Any

# Что сверяем и с каким допуском. Список один на обе пары: разойдись он, одна
# площадка проверялась бы по трём величинам, а соседняя по двум, и обе
# выглядели бы проверенными.
FIELDS: tuple[tuple[str, str, float], ...] = (
    ("area_ha", "площадь территории", 0.02),
    ("total_gfa_sqm", "общий объём", 0.02),
    ("housing_gfa_sqm", "жильё", 0.02),
)


def compare(ours: dict[str, Any], theirs: dict[str, Any], *,
            ours_label: str, theirs_label: str,
            fields: tuple[tuple[str, str, float], ...] = FIELDS) -> dict[str, Any]:
    """Сверить две стороны и назвать обе: чьё число где, видно в самой строке."""
    compared: list[str] = []
    problems: list[str] = []
    for key, name, tolerance in fields:
        left, right = ours.get(key), theirs.get(key)
        if left is None or right is None:
            continue
        compared.append(name)
        base = max(abs(float(right)), 1.0)
        if abs(float(left) - float(right)) / base > tolerance:
            problems.append(
                f"{name}: {ours_label} {float(left):g}, {theirs_label} {float(right):g}")
    return {"compared": compared, "problems": problems}
