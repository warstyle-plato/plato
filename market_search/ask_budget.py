"""Бюджет вопроса Платону — одна реализация на все поверхности.

Предел у Платона 4000 знаков, и считать его надо на ВСЁ сообщение, а не на его
середину. Свод продаж этому научили 26.08.2026: обязательная шапка с выводами и
хвост со списком непрочитанного стояли вне счёта, и на полностью загруженном
проекте вопрос перевалил предел ещё до первого раздела — кнопка отвечала
«Вопрос слишком длинный» именно там, где данных больше всего.

Модуль торгов ту же болезнь получил в наследство и в чистом виде: свод там
собирался вовсе без бюджета. На семнадцати лотах с длинными названиями и
выбранной площадкой, у которой в описании перечислены ЗОУИТ и охранные зоны,
сообщение уходило за четыре тысячи, и человек видел отказ на вопрос в две
строки (владелец, 31.08.2026).

Поэтому алгоритм живёт здесь один и подставляется обеим страницам, как подвал
и версия: копию негде обновлять, потому что копии нет. Правила его — из
разборов, а не из вкуса:

* **место под строку «не поместилось» держится с начала.** Приписанная сверх
  бюджета, она обрезалась первой — пропадало ровно то предупреждение, ради
  которого она написана, а свод выглядел полным;
* **раздел входит построчно, а не целиком.** Всё-или-ничего выбрасывало раздел
  из шести строк и пускало стоящий ниже из пяти: из вопроса исчезали темы, о
  которых мы же и спросили;
* **метка «вошло N из M» ставится, если для неё есть место, и НЕ вместо
  данных.** Подмена последней строки меткой оставляла раздел из одной строки
  «(вошло 1 из 8)»;
* **обрезка называет себя.** Молча укороченный свод читается как полный.

Порядок разделов задаёт зовущий: у продаж он свой, у торгов свой. Здесь только
счёт.
"""

from __future__ import annotations

PLACEHOLDER = "__DEVELOPAID_ASK_BUDGET__"

SCRIPT = """
// Бюджет вопроса Платону. Объявлен один раз в market_search/ask_budget.py и
// подставляется обеим страницам — своду продаж и торгам.
//
// head   — обязательные строки, они входят всегда;
// groups — [{name, lines}] в том порядке, в каком их хочет видеть зовущий;
// cap    — сколько знаков всего можно занять.
function fitAsk(head, groups, cap){
  cap=Number(cap)||2800;
  // Место под строку «не поместилось» держится с самого начала. Приписанная
  // сверх бюджета, она вылезала за предел и обрезалась первой — то есть
  // пропадало ровно то предупреждение, ради которого она написана, а свод
  // выглядел полным.
  const NOTE_ROOM=200;
  const kept=[...head], dropped=[];
  let size=kept.join('\\n').length;
  (groups||[]).forEach(g=>{
    if(!g||!g.lines||!g.lines.length) return;
    // Раздел входит построчно, а не целиком. Всё-или-ничего давало обрыв:
    // раздел из шести строк не влезал, а стоящий ниже из пяти влезал — и из
    // вопроса выпадали темы, о которых мы же и спросили. Сколько строк вошло
    // из скольких, стоит в самой строке.
    const room=cap-NOTE_ROOM-size;
    const fit=[];
    let used=0;
    g.lines.forEach(line=>{
      if(used+line.length+1<=room){ fit.push(line); used+=line.length+1 }
    });
    if(!fit.length){ dropped.push(g.name+' ('+g.lines.length+' строк)'); return }
    if(fit.length<g.lines.length){
      const note='(вошло '+fit.length+' строк из '+g.lines.length+')';
      // Метка ставится, если для неё есть место, и НЕ вместо данных: подмена
      // последней строки меткой оставляла раздел из одной строки «(вошло 1 из
      // 8)» — то есть выбрасывала ровно то, ради чего раздел вошёл. Что раздел
      // урезан, в любом случае сказано общей строкой ниже.
      if(used+note.length+1<=room){ fit.push(note); used+=note.length+1 }
      dropped.push(g.name+' — часть');
    }
    kept.push(fit.join('\\n'));
    size+=fit.join('\\n').length+1;
  });
  if(dropped.length){
    let note='НЕ ПОМЕСТИЛОСЬ В ВОПРОС (не считай это отсутствием данных): '+dropped.join(', ')+'.';
    if(note.length>NOTE_ROOM-1) note=note.slice(0,NOTE_ROOM-3)+'….';
    kept.push(note);
  }
  // Последний рубеж: даже обязательная шапка теоретически может перерасти
  // бюджет (длинное имя проекта, длинное название лота). Обрезка называет
  // себя — молча укороченный свод читается как полный.
  let out=kept.join('\\n');
  if(out.length>cap) out=out.slice(0, Math.max(0, cap-40))+'\\n(свод обрезан по длине вопроса)';
  return out;
}
"""
