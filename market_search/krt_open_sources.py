# Сокращения адреса, которых в публикациях не бывает. Каталог пишет «Светлый
# проезд, вл. 4», dzen — «Светлый проезд, 4», канал — «Светлый проезд, вл. 4»:
# точная фраза с «вл.» не совпадает с первым вовсе.
# Точка после сокращения — часть сокращения, и «\b» её не захватывает: между
# «.» и пробелом границы слова нет, поэтому «вл.» превращалось в «.» посреди
# адреса. Границы заданы явно.
_ADDRESS_NOISE = re.compile(
    r"(?iu)(?<!\w)(?:вл|влд|владение|д|дом|стр|строение|корп|корпус|"
    r"тер|территория|уч|участок)\.?(?!\w)")
# Осколки, оставшиеся от выброшенных сокращений.
_ADDRESS_DEBRIS = re.compile(r"(?u)(?<!\w)[.,;]+(?!\w)")


def search_address(name: str) -> str:
    """Адрес площадки в том виде, в каком его пишут люди.

    Каталог города пишет по-канцелярски — «Молдавская ул., вл. 3-5», — а
    публикации живым языком. Сокращения выбрасываются, запятые тоже: они в
    запросе ничего не значат, а точную фразу рвут.
    """
    flat = _ADDRESS_NOISE.sub(" ", str(name or ""))
    flat = flat.replace(",", " ").replace("«", " ").replace("»", " ")
    flat = _ADDRESS_DEBRIS.sub(" ", flat)
    return _SPACE.sub(" ", flat).strip(" -–—.")


# Тип улицы: по нему видно, где кончился один адрес и начался другой. Стоит он
# и перед именем («ул. Удальцова»), и после него («Молдавская ул.»), поэтому
# ищется как слово, а не как приставка.
_STREET_TYPE = re.compile(
    r"(?iu)(?<!\w)(?:ул|улица|пр-т|просп|проспект|проезд|пер|переулок|наб|"
    r"набережная|б-р|бульвар|ш|шоссе|пл|площадь|туп|тупик|аллея|линия)\.?(?!\w)")


def search_addresses(name: str) -> list[str]:
    """Адреса площадки по отдельности: их бывает несколько.

    У площадки КРТ в каталоге города имя — это перечисление адресов:
    «ул. Удальцова, влд. 75А, ул. Веерная, влд. 1». Склеенные в один запрос,
    они дают строку, которой нет ни в одной публикации, — поиск отвечает про
    что угодно. Спрашивать надо по каждому адресу и складывать находки.

    Новый адрес начинается там, где снова назван тип улицы, а у предыдущего
    уже есть номер: «Молдавская ул., вл. 3-5» — это ОДИН адрес, и разрывать
    его по запятой нельзя.
    """
    parts = [part.strip() for part in str(name or "").split(",")]
    chunks: list[list[str]] = []
    for part in parts:
        if not part:
            continue
        started = bool(chunks)
        has_number = started and any(ch.isdigit() for ch in " ".join(chunks[-1]))
        if started and has_number and _STREET_TYPE.search(part):
            chunks.append([part])
        elif started:
            chunks[-1].append(part)
        else:
            chunks.append([part])
    out: list[str] = []
    for chunk in chunks:
        clean = search_address(", ".join(chunk))
        if clean and clean not in out:
            out.append(clean)
    return out


def queries(name: str, okrug: str = "", district: str = "") -> list[str]:
    """Запросы к поиску. Имя площадки — это её адрес, и он же якорь находки.

    Спрашиваем ВОПРОСОМ, а не набором слов (владелец, 01.09.2026: «даже тупая
    Алиса находит легко, когда задаёшь вопрос, кто оператор или кто строит КРТ
    по такому адресу»). Прежние запросы были двух видов сразу неудачных: адрес
    брался в жёсткие кавычки — точной фразой, которой в публикациях нет, — и
    рядом стояло одно слово «оператор», хотя пишут «застройщик», «девелопер»,
    «построит».

    Кавычек больше нет намеренно. Мусор, который они отсекали, отсекает якорь:
    признак ставится только в предложении с адресом площадки, а что прочитано и
    что отброшено, теперь видно в карточке.
    """
    addresses = search_addresses(name)
    where = " ".join(part for part in (district, okrug) if part)
    # Имя площадки бывает не адресом, а перечнем общих слов: «Магистральные
    # улицы тер. 4, 5, 6». По нему поиск отвечает про городские магистрали
    # вообще, а пишут о такой площадке по району и по соседству — «промзона
    # рядом с Москва-Сити» (владелец, 02.09.2026). Тогда спрашиваем районом:
    # это единственное, чем она названа однозначно.
    words, phrase = _site_anchor(name)
    if not words:
        if not where:
            return []
        # Имя всё же спрашиваем, если из него вышла фраза: по ней площадку
        # называют в публикациях. Район идёт рядом, а не вместо — о такой
        # площадке пишут и «промзона рядом с Москва-Сити».
        # Спрашиваем словами имени, а не их основами: «Магис Улицы» — не то, что
        # написано в публикациях, а поиск ищет по написанному.
        said = " ".join(_phrase_words(name))
        asked = [f"кто застройщик КРТ {where} район Москва",
                 f"комплексное развитие территории {where} Москва оператор проекта"]
        if said:
            asked.insert(0, f"кто оператор и застройщик КРТ {said} {where} Москва")
        return asked[:3]
    if not addresses:
        return []
    out: list[str] = []
    # Адресов у площадки бывает несколько, и спрашиваем по каждому: склеенные в
    # одну строку, они дают запрос, которого нет ни в одной публикации.
    # Спрашиваем ВОПРОСОМ, а не набором слов.
    for base in addresses[:2]:
        out.append(f"кто оператор и застройщик КРТ по адресу {base} Москва")
        # Второй путь к тому же ответу, и часто он короче: справочники и
        # объявления отвечают на «что здесь строится» именем ЖК, а от имени до
        # компании один шаг — им же идёт наш круг по бренду (владелец,
        # 01.09.2026: «там указано, что по этому адресу строится конкретный ЖК
        # Строгино 360»).
        out.append(f"какой ЖК строится по адресу {base} Москва девелопер")
    if where:
        out.append(f"{addresses[0]} {where} комплексное развитие территории договор заключён")
    # Потолок — поиск платный, и площадка с пятью адресами не имеет права
    # стоить впятеро дороже соседней.
    return out[:5]


# Телеграм-каналы застройщиков и городские каналы говорят о площадке раньше
# деловой прессы и почти всегда именем проекта, а не адресом. Спрашиваются они
# тем же платным индексом, ограниченным доменом: своего пути наружу модуль не
# заводит — правило то же, по которому поиск взят у движка рынка.
#
# Круг ровно один и по одному якорю: у поиска цена за запрос, а канал без
# якоря в том же предложении дал бы то же, что сниппет, повторяющий запрос.
def telegram_queries(name: str, brands: Iterable[str] = ()) -> list[str]:
    """Запрос к каналам: по имени проекта, если оно доказано, иначе по адресу."""
    brand = next((str(b).strip() for b in (brands or []) if str(b).strip()), "")
    if brand:
        return [f'site:t.me "{brand}" КРТ застройщик оператор']
    addresses = search_addresses(name)
    if not addresses:
        return []
    # Адрес — без канцелярских сокращений и без кавычек: в канале пишут живым
    # языком, и точная фраза каталога там не встречается. Адресов бывает
    # несколько, и склеенные в один запрос они не совпадают ни с чем.
    return [f"site:t.me кто оператор КРТ {base} застройщик" for base in addresses[:2]]


def _anchor_words(name: str) -> set[str]:
    """Основы слов площадки: «Молдавская» и «на Молдавской улице» — одно место.

    Сравнивать словоформы целиком нельзя: русский падеж рассыпает совпадение, и
    якорь не срабатывает ровно там, где публикация написана живым языком.
    """
    flat = str(name or "").lower().replace("ё", "е")
    # Слова, которыми площадку не опознать: они стоят в каждой второй статье о
    # городе. «Магистральные улицы тер. 4, 5, 6» — настоящее имя площадки в
    # каталоге, и якорем из него выходило «магис» + «улицы»: под такой якорь
    # подходит любая проза про московские магистрали, и в карточку приезжала
    # статья про Москва-Сити и «реновацию локации в 3 тыс. га» (экран
    # владельца, 02.09.2026). Признак, который срабатывает на чужом тексте, —
    # не признак.
    stop = {"улица", "улице", "улиц", "улицы", "улицам", "магистральные",
            "магистральная", "магистральных", "магистраль", "проезд", "проезде",
            "проезды", "переулок", "владение", "москва", "московский",
            "территория", "территории", "территорий", "проект", "участок",
            "участка", "город", "тер", "влд", "квартал", "квартала",
            "кварталы", "промзона", "промзоны", "район", "района", "округ",
            "зона", "зоны", "шоссе", "набережная", "бульвар", "площадь",
            "линия", "аллея", "тупик", "корпус", "строение", "дом"}
    # Пять букв, а не шесть. «Светлый» даёт основу «светлы», а публикация пишет
    # «на Светлом проезде» — «светлом» с неё не начинается, и якорь не
    # срабатывал ровно на той площадке, из-за которой всё и затевалось
    # (владелец, 01.09.2026). Шестая буква у прилагательного — уже окончание.
    return {word[:5] for word in _WORD.findall(flat) if word not in stop}


_PHRASE_SKIP = {"тер", "территория", "территории", "влд", "вл", "д", "дом",
                "стр", "корп", "участок", "москва", "город"}


def _phrase_words(name: str) -> list[str]:
    """Значимые слова имени как есть — ими и спрашивают поиск."""
    return [word for word in _WORD.findall(str(name or ""))
            if word.lower().replace("ё", "е") not in _PHRASE_SKIP
            and not word.isdigit() and len(word) > 2][:4]


def _phrase_anchor(name: str) -> list[str]:
    """Основы слов имени ПО ПОРЯДКУ — якорь для имени из общих слов.

    «Магистральные улицы тер. 4, 5, 6»: по отдельности «магис» и «улицы»
    ловят любую прозу о городе, а подряд — только тот текст, где площадка
    названа своим именем. Настоящая публикация о ней так и пишет: «Оператором
    выступает компания „КРТ «Магистральные улицы»“». Отбрасывать её вместе с
    чужой значило бы лечить ложную находку потерей настоящей.
    """
    return [word.lower().replace("ё", "е")[:5] for word in _phrase_words(name)]


def _mentions_phrase(sentence: str, stems: list[str]) -> bool:
    """Стоят ли основы имени в этом предложении подряд, в том же порядке."""
    if len(stems) < 2:
        return False
    words = _WORD.findall(sentence.lower().replace("ё", "е"))
    for start in range(len(words) - len(stems) + 1):
        if all(words[start + shift].startswith(stem)
               for shift, stem in enumerate(stems)):
            return True
    return False


# Номер владения: «Фестивальная ул., вл. 53А» и «Фестивальная ул., вл. 6, 6а,
# 6б, 4а» — РАЗНЫЕ площадки на одной улице, и обе в каталоге. Якорь держал
# только улицу, поэтому оператор одной приезжал в карточку другой: «Бореалис —
# это про 6а, 6б, а не про 53А» (владелец, 02.09.2026). Улица одна и та же —
# отличает их номер.
_HOUSE = re.compile(
    r"(?iu)(?:вл|влд|владение|дом|д)\.?\s*№?\s*(\d+[а-яa-z]?(?:\s*[/,-]\s*\d+[а-яa-z]?)*)")
_HOUSE_ITEM = re.compile(r"(?iu)\d+[а-яa-z]?")


def _house_numbers(text: str) -> set[str]:
    """Номера владений, названные в тексте. Пусто — номер не назван вовсе."""
    out: set[str] = set()
    for found in _HOUSE.finditer(str(text or "")):
        for item in _HOUSE_ITEM.findall(found.group(1)):
            out.add(item.lower().replace("ё", "е"))
    return out


# Публикация пишет адрес по-человечески: «ЖК от STONE на Светлый проезд, 4»,
# без «вл.». Требовать сокращение значило бы не увидеть номер там, где он
# написан прямо. Единица измерения рядом снимает совпадение: «55 тыс. м²» —
# это площадь, а не владение.
_UNIT_AFTER = re.compile(
    r"(?iu)^\s*(?:тыс|млн|млрд|га|кв|м2|м²|%|проц|лет|год|мест|машино|руб|₽|"
    r"этаж|секц|корп|дом(?:ов)?|квартир|человек|жител)")


def _says_our_number(sentence: str, ours: set[str]) -> bool:
    """Назван ли в предложении НАШ номер владения — хоть с «вл.», хоть без."""
    if not ours:
        return False
    if _house_numbers(sentence) & ours:
        return True
    flat = str(sentence or "").lower().replace("ё", "е")
    for number in ours:
        for found in re.finditer(
                rf"(?<![\w./,-]){re.escape(number)}(?![\w./-])", flat):
            if not _UNIT_AFTER.match(flat[found.end():]):
                return True
    return False


def _house_conflict(sentence: str, ours: set[str]) -> bool:
    """Названы ли в предложении ДРУГИЕ номера владений и только они.

    Номер, названный в тексте и не совпавший с нашим, — это соседняя площадка.
    Текст без номеров вовсе конфликтом не считается: об одной территории часто
    пишут просто «на Фестивальной», и требовать номер значило бы выбрасывать
    настоящие находки.
    """
    if not ours:
        return False
    theirs = _house_numbers(sentence)
    return bool(theirs) and not (theirs & ours)


def _site_anchor(name: str) -> tuple[set[str], list[str]]:
    """Чем опознавать площадку: основы слов или, если они общие, — фраза.

    Возвращает пару «слова, фраза». Слова сильнее: они переживают падеж и
    перестановку. Фраза — запасной якорь для имени вроде «Магистральные улицы
    тер. 4, 5, 6», у которого своих слов нет вовсе.
    """
    words = _anchor_words(name)
    return (words, [] if words else _phrase_anchor(name))


def _mentions(sentence: str, anchors: set[str]) -> bool:
    """Сказано ли в этом предложении о НАШЕЙ площадке.

    Пустой набор якорей значит «опознать площадку нечем», а не «подходит
    любой текст». Прежде было наоборот, и у площадки с общим именем — вроде
    «Магистральные улицы тер. 4, 5, 6» — в признаки шло всё подряд: якорей не
    оставалось после чистки, и проверка пропускала каждое предложение.
    Отсутствие якоря — причина ничего не утверждать, а не разрешение.
    """
    if not anchors:
        return False
    words = _WORD.findall(sentence.lower().replace("ё", "е"))
    return any(word.startswith(stem) for word in words for stem in anchors)


# Имя проекта рынком известно раньше адреса: «Строгино 360» знают все, а
# «Маршала Воробьева ул., вл. 12» — никто. Статья про бренд к площадке не
# привязывалась вовсе: якорем служит адрес, и это дыра, а не осторожность
# (владелец, 01.09.2026: «по улице Маршала Воробьева 12 не показывает, что оно
# обещано кому-то, а там же Строгино 360 и это ПИК»).
#
# Бренд берётся только доказанный: он обязан стоять в ОДНОМ предложении с
# адресом площадки. Иначе повторится ошибка модуля рынка, где сниппет,
# повторяющий запрос, отдавал каждому кандидату адрес объекта оценки.
_BRAND = re.compile(
    r"(?:ЖК|жилой комплекс|жилого комплекса|проект|проекта|квартал)\s+"
    r"[«\"]([^«»\"]{3,40})[»\"]"
    r"|[«\"]([А-ЯЁA-Z][^«»\"]{2,39})[»\"]")
# Слова, которые в кавычках стоят, но именем проекта не являются.
_NOT_BRAND = {"крт", "комплексное развитие территории", "реновация", "москва",
              "планируемый", "в реализации", "проект решения"}


# Имя компании в кавычках — не имя проекта. «Оператором стала ГК „Орехово“»:
# отсюда бралось «Орехово» как бренд площадки, бренд становился вторым якорем,
# и якорь подтверждал ту самую находку, из которой он же и вышел. Кольцо —
# оператор доказывал сам себя, и «ГК Орехово» приезжала на Шипиловский, 55 из
# статьи про Шипиловский, 39 (владелец, 02.09.2026).
_COMPANY_BEFORE = re.compile(
    r"(?iu)(?:гк|ооо|оао|зао|пао|ао|нао|ук|сз|тк|гбу|гку|кп|фонд|группа(?:\s+компаний)?|"
    r"компания|компании|девелопер|застройщик|холдинг|концерн|корпорация)\s*$")


def _named_by_a_company(sentence: str, found: "re.Match[str]") -> bool:
    """Стоит ли перед кавычками форма юрлица — тогда это компания, не проект."""
    return bool(_COMPANY_BEFORE.search(sentence[:found.start()].rstrip()))


def brand_names(docs: Iterable[Any], name: str) -> list[str]:
    """Как площадка называется на рынке — по соседству с её адресом.

    Пусто — значит пусто: имя, взятое из предложения без адреса, привязало бы
    к площадке чужой проект.
    """
    anchors, phrase = _site_anchor(name)
    houses = _house_numbers(name)
    found: list[str] = []
    for doc in docs or []:
        text = f"{getattr(doc, 'title', '')}. {getattr(doc, 'snippet', '')}"
        for sentence in _sentences(text):
            if not (_mentions(sentence, anchors)
                    or _mentions_phrase(sentence, phrase)):
                continue
            # Улица совпала, а номер владения — чужой: это соседняя площадка.
            if _house_conflict(sentence, houses):
                continue
            for match in _BRAND.finditer(sentence):
                brand = (match.group(1) or match.group(2) or "").strip()
                low = brand.lower().replace("ё", "е")
                if not brand or low in _NOT_BRAND:
                    continue
                # Имя, состоящее из слов самого адреса, вторым якорем не
                # является: оно ничего не добавляет.
                if _mentions(brand, anchors):
                    continue
                # Компания, а не проект: иначе оператор становится якорем
                # площадки и подтверждает сам себя.
                if _named_by_a_company(sentence, match):
                    continue
                if brand not in found:
                    found.append(brand)
    return found[:3]


# Сокращения, после которых точка — не конец фразы. Адрес площадки сам состоит
# из них: «Маршала Воробьева ул., вл. 12» разваливалось пополам, адрес уезжал в
# одно предложение, признак — в другое, и правило «в одном предложении» молча
# теряло настоящую находку на КАЖДОМ адресе с «вл.» (владелец, 01.09.2026).
_ABBR = {"вл", "влд", "д", "дом", "стр", "корп", "к", "тер", "кв", "ул", "просп",
         "пр", "пер", "наб", "ш", "г", "гг", "руб", "тыс", "млн", "млрд", "им",
         "обл", "мкр", "п", "с", "им", "т", "ок", "прим", "рис", "см"}
_TAIL_WORD = re.compile(r"([А-Яа-яЁёA-Za-z]+)\.$")


def _sentences(text: str) -> list[str]:
    flat = _SPACE.sub(" ", str(text or "")).strip()
    parts = [part.strip() for part in _SENTENCE.split(flat) if part.strip()]
    out: list[str] = []
    for part in parts:
        if out:
            tail = _TAIL_WORD.search(out[-1])
            short = tail and tail.group(1).lower().replace("ё", "е") in _ABBR
            # Точка после сокращения или перед числом фразу не кончает:
            # «вл. 12», «д. 5 стр. 2», «тыс. кв. м».
            if short or part[:1].isdigit():
                out[-1] = out[-1] + " " + part
                continue
        out.append(part)
    return out


def _clean_name(raw: str) -> str:
    """Имя без внешних кавычек. Внутренние остаются: «АО «Стоунхедж»» — одно имя.

    Голый `strip(" «»")` срезал закрывающую кавычку и оставлял «АО «Стоунхедж» —
    имя с непарной кавычкой, которое дальше ни с чем не совпадёт.
    """
    name = _SPACE.sub(" ", str(raw or "")).strip()
    while name.startswith("«") and name.endswith("»"):
        name = name[1:-1].strip()
    return name


def _is_not_an_operator(name: str) -> bool:
    """Поставщик данных или издание — не оператор площадки, а источник о ней."""
    low = str(name or "").lower().replace("ё", "е")
    return any(mark in low for mark in _NOT_AN_OPERATOR)


# Кавычки — не признак компании: в них же стоят станции метро и улицы.
# «Оператор КРТ у метро «Коломенская»» давало оператора «Коломенская»
# (экран владельца, 02.09.2026). Место узнаётся по слову перед кавычками и по
# форме имени: одно слово-прилагательное — топоним, а не юрлицо.
_PLACE_BEFORE = re.compile(
    r"(?iu)(?:метро|станци\w*|ст\.\s*м\.|м\.|улиц\w*|ул\.|район\w*|платформ\w*|"
    r"площад\w*|шоссе|проспект\w*|пр-т|набережн\w*|бульвар\w*|деревн\w*|посёлк\w*|"
    r"поселк\w*|город\w*|округ\w*)\s*$")
_TOPONYM_WORD = re.compile(r"(?u)^«?[А-ЯЁ][а-яё-]+(?:ская|ский|ское|ские|ская|цкая|цкий|ное|ный|ная)»?$")


def _looks_like_a_place(tail: str, found: "re.Match[str]") -> bool:
    """Имя в кавычках — место, а не компания."""
    before = tail[:found.start()]
    if _PLACE_BEFORE.search(before):
        return True
    raw = found.group("name").strip()
    return bool(_TOPONYM_WORD.match(raw))


def _operator_name(sentence: str) -> str:
    """Имя оператора. Нет имени — пустая строка, а не догадка."""
    word = _OPERATOR_WORD.search(sentence)
    if word:
        tail = sentence[word.end():word.end() + 140]
        found = _NAME.search(tail)
        if found and not _looks_like_a_place(tail, found):
            name = _clean_name(found.group("name"))
            if name and not _is_not_an_operator(name):
                return name
    # «ЖК от STONE» — то же утверждение другой формой: имя стоит перед адресом,
    # и хвостовой разбор его не достаёт.
    branded = _BRAND_OF.search(sentence)
    if branded:
        name = _clean_name(branded.group("name"))
        low = name.lower().rstrip("аеиоуыюя")
        if (name and not any(low.startswith(stem[:6]) for stem in _NOT_A_BRAND)
                and not _is_not_an_operator(name)):
            return name
    return ""


def _is_telegram(domain: str) -> bool:
    host = str(domain or "").lower().strip().strip(".")
    return host == "t.me" or host.endswith(".t.me") or host == "telegram.me"


def _found(sentence: str, doc: Any) -> dict[str, Any]:
    domain = getattr(doc, "domain", "") or ""
    return {
        "quote": sentence[:400],
        "url": getattr(doc, "url", "") or "",
        "domain": domain,
        "official": any(host in domain for host in _TRUSTED),
        # Канал — не издание: пост пишет кто угодно, опровергать его никто не
        # обязан. Признак ставится тот же и по тому же правилу (цитата, ссылка,
        # якорь в том же предложении), но происхождение названо вслух — иначе
        # слух встанет на экране рядом с mos.ru и будет выглядеть так же.
        "telegram": _is_telegram(domain),
    }


# Версия правила привязки находки к площадке. Хранимый ответ — не вечный: он
# посчитан ПРАВИЛОМ, и когда правило меняется, прежний ответ перестаёт быть
# ответом. Занятость спрашивается один раз («отданная площадка свободной не
# становится»), поэтому неверная находка иначе живёт вечно: «Бореалис» стоял у
# Фестивальной, 53А, хотя строит он 6, 6а, 6б (владелец, 02.09.2026), и
# перечитывать её было незачем — она же «занята».
#   1 — якорем служила улица;
#   2 — на улице с несколькими площадками каталога нужен номер владения;
#   3 — тяжёлые признаки (оператор, договор, городские нужды) требуют номер
#       владения или имя проекта всегда, даже когда соседа в каталоге нет.
ANCHOR_RULES_VERSION = 3


def read_findings(
    docs: Iterable[Any], name: str, siblings: Iterable[str] = ()
) -> dict[str, Any]:
    """Разобрать выдачу по одной площадке. Без цитаты признак не ставится.

    `siblings` — имена остальных площадок каталога. По ним видно, опознаёт ли
    улица площадку вообще. «Варшавское шоссе, вл. 37, Нагатинская ул., влд.
    3А/6» давало якоря «варша» и «нагат»: под них подходит любая статья про
    Нагатино и про пятнадцать километров Варшавки, и в карточку приехали чужая
    реновация и чужой застройщик (владелец, 02.09.2026: «мы анализировали
    Нагатинскую, там нет ни реновации, ни ФСК»).

    Правило то же, что у геокодера: якорь обязан быть не менее точным, чем то,
    что он опознаёт. Улица, на которой стоит ещё одна площадка каталога,
    площадку не опознаёт — засчитывается только упоминание с НАШИМ номером
    владения либо с доказанным именем проекта. Улица, где площадка одна,
    работает как прежде: требовать номер там значило бы терять настоящие
    находки — «на Фестивальной» пишут и без номера.
    """
    anchors, phrase = _site_anchor(name)
    anchors = set(anchors)
    houses = _house_numbers(name)
    neighbours: set[str] = set()
    for other in siblings or ():
        if str(other or "").strip() and str(other) != str(name):
            neighbours |= _anchor_words(other)
    shared = anchors & neighbours
    strict = bool(houses) and bool(shared)
    # Бренд площадки, если он доказан соседством с адресом, работает якорем
    # наравне с адресом: статья, где сказано только «Строгино 360», иначе
    # проходит мимо.
    docs = list(docs or [])
    brands = brand_names(docs, name)
    brand_anchors: set[str] = set()
    for brand in brands:
        brand_anchors |= _anchor_words(brand)
    anchors |= brand_anchors

    def named_ours(sentence: str) -> bool:
        """Назван ли в предложении наш номер владения либо имя проекта."""
        if _says_our_number(sentence, houses):
            return True
        return bool(brand_anchors) and _mentions(sentence, brand_anchors)
    operator_named: list[dict[str, Any]] = []
    operator_appointed: list[dict[str, Any]] = []
    operator_pending: list[dict[str, Any]] = []
    city_needs: list[dict[str, Any]] = []
    agreement: list[dict[str, Any]] = []
    stage: list[dict[str, Any]] = []
    seen: set[str] = set()
    checked = 0
    for doc in docs or []:
        checked += 1
        text = f"{getattr(doc, 'title', '')}. {getattr(doc, 'snippet', '')}"
        # Номер владения доказывается ДОКУМЕНТОМ, а не предложением: настоящая
        # публикация называет адрес в заголовке, а оператора в тексте, и
        # требовать номер в той же фразе значило бы терять почти все находки.
        # Чужой номер при этом отсекается конфликтом ниже — так же, как раньше.
        proved = named_ours(text)
        for sentence in _sentences(text):
            low = sentence.lower().replace("ё", "е")
            # Якорь площадки в ТОМ ЖЕ предложении: сниппет повторяет запрос, и
            # без якоря сюда попадает любой соседний проект.
            if not (_mentions(sentence, anchors)
                    or _mentions_phrase(sentence, phrase)):
                continue
            # Улица совпала, а номер владения — чужой: это соседняя площадка.
            if _house_conflict(sentence, houses):
                continue
            # Улица общая с соседней площадкой каталога: без нашего номера или
            # имени проекта предложение — о соседях, а не о нас.
            if strict and not named_ours(sentence):
                continue
            key = low[:120]
            if key in seen:
                continue
            seen.add(key)
            # Чем тяжелее утверждение, тем строже доказательство. «Оператор
            # назван», «договор заключён» и «городские нужды» закрывают вход на
            # площадку — их ставим ТОЛЬКО при названном номере владения или
            # имени проекта, даже если соседа по улице в каталоге нет вовсе.
            # «Ты на Шипиловском 55 пишешь, что там ГК Орехово, а это
            # Шипиловский 39» (владелец, 02.09.2026), и тридцать девятого в
            # реестре нет: улица нашлась, номер никто не спрашивал.
            #
            # Цена названа: на улице, где площадка одна, статья без номера
            # («оператором на Никулинской стало…») в признак больше не идёт.
            # Она остаётся в прочитанном и видна — но приписать по ней
            # застройщика значит однажды приписать чужого.
            heavy_ok = (proved or named_ours(sentence)) if houses else True
            named = _operator_name(sentence)
            if named and heavy_ok:
                item = _found(sentence, doc)
                item["name"] = named
                operator_named.append(item)
            elif not named and any(mark in low for mark in _APPOINTED) and heavy_ok:
                operator_appointed.append(_found(sentence, doc))
            elif not named and any(mark in low for mark in _TO_BE_CHOSEN):
                # «Право ещё выставят на торги» говорит, что площадка СВОБОДНА:
                # вход оно не закрывает, и строгость тут была бы потерей.
                operator_pending.append(_found(sentence, doc))
            if any(mark in low for mark in _CITY_NEEDS) and heavy_ok:
                city_needs.append(_found(sentence, doc))
            if any(mark in low for mark in _AGREEMENT) and heavy_ok:
                agreement.append(_found(sentence, doc))
            if any(mark in low for mark in _STAGE):
                stage.append(_found(sentence, doc))
    # «Оператор назван» и «оператор назначен» — разные ответы, и второй не
    # отменяется первым: имя может быть в одной публикации, а факт назначения в
    # другой. Пустой список значит «не нашли», а не «нет».
    return {
        "checked": checked,
        "rules_version": ANCHOR_RULES_VERSION,
        # Что поиск ВООБЩЕ принёс. Без этого «не нашли» и «нечего было
        # находить» на экране неразличимы: читатель видит пустой блок и не
        # может сказать, промолчал источник или промолчали мы. Владелец трижды
        # подряд присылал публикацию, которую видно глазами, — и каждый раз
        # разговор начинался с догадок вместо выдачи (01.09.2026).
        "documents": [
            {"title": str(getattr(doc, "title", "") or "")[:200],
             "url": str(getattr(doc, "url", "") or ""),
             "domain": str(getattr(doc, "domain", "") or ""),
             # Конфликт номеров считается по документу целиком: заголовок
             # «КРТ на Фестивальной» номера не называет, а сниппет называет
             # чужой — это статья о соседе, и привязанной она быть не может.
             "anchored": (not _house_conflict(
                 f"{getattr(doc, 'title', '')}. {getattr(doc, 'snippet', '')}", houses)
                 and any((_mentions(one, anchors) or _mentions_phrase(one, phrase))
                         and (not strict or named_ours(one))
                         for one in _sentences(
                             f"{getattr(doc, 'title', '')}. {getattr(doc, 'snippet', '')}")))}
            for doc in docs[:20]
        ],
        # Чем опознавалась площадка. Пусто — значит имя каталога состоит из
        # общих слов («Магистральные улицы тер. 4, 5, 6»), и привязать к ней
        # находку нечем: прочитанное показываем, но признаков не ставим.
        # Молча пустой блок читался бы как «в источниках ничего нет».
        "anchors": sorted(anchors) or [" ".join(phrase)] if (anchors or phrase) else [],
        "anchorless": not anchors and not phrase,
        # Улица общая с соседней площадкой каталога — засчитываем только
        # упоминания с номером владения или именем проекта. Молчание такого
        # разбора иначе читалось бы как «в источниках ничего нет».
        "strict_house": strict,
        "shared_anchors": sorted(shared),
        "house_numbers": sorted(houses),
        "operator_named": operator_named[:3],
        "operator_appointed": operator_appointed[:3],
        "operator_pending": operator_pending[:3],
        "city_needs": city_needs[:3],
        # Договор заключён — отдельный ответ, а не разновидность стадии.
        "agreement": agreement[:3],
        "stage": stage[:4],
        # Как площадка известна рынку: имя проекта, доказанное соседством с
        # адресом. По нему идёт второй круг поиска — статья про бренд адреса
        # чаще всего не называет.
        "brands": brands,
        # Сколько находок пришло из каналов: пустая строка «спросили каналы, и
        # там пусто» и не спрошенные вовсе каналы выглядят на экране одинаково.
        "telegram_found": sum(
            1 for item in operator_named + operator_appointed + operator_pending
            + city_needs + agreement + stage if item.get("telegram")),
        # Заключённый договор занимает площадку так же, как названный оператор:
        # «Планируемая» в каталоге значит «стройка не начата», а не «свободна».
        "taken": bool(operator_named or operator_appointed or agreement),
        "free": bool(operator_pending)
        and not (operator_named or operator_appointed or agreement),
    }
