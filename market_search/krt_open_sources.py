# Версия правила привязки находки к площадке. Хранимый ответ — не вечный: он
# посчитан ПРАВИЛОМ, и когда правило меняется, прежний ответ перестаёт быть
# ответом. Занятость спрашивается один раз («отданная площадка свободной не
# становится»), поэтому неверная находка иначе живёт вечно: «Бореалис» стоял у
# Фестивальной, 53А, хотя строит он 6, 6а, 6б (владелец, 02.09.2026), и
# перечитывать её было незачем — она же «занята».
#   1 — якорем служила улица;
#   2 — на улице с несколькими площадками каталога нужен номер владения;
#   3 — тяжёлые признаки (оператор, договор, городские нужды) требуют номер
#       владения или имя проекта всегда, даже когда соседа в каталоге нет;
#   4 — оператор, застройщик и Фонд разведены по методике владельца, торги
#       считаются только на право договора КРТ, у находки есть надёжность.
#   5 — заведена корзина «здесь уже продаётся ЖК» (доказательство — наш номер
#       владения в документе), а имя компании больше не тащит хвост заголовка.
#   6 — имя того, кто здесь строит, засчитывается только в документе про КРТ:
#       страница продаж построенного дома называет застройщика ЭТОГО дома, а
#       номер у владения и у дома один и тот же. И одинокая цифра больше не
#       якорь — она совпадает с чем угодно.
# 7: номер владения доказывается только в АДРЕСНОЙ позиции (любой, а не одна
# цифра), «корпус N» номером владения не считается, а якорь, общий с соседней
# площадкой списка, у площадки без номера снимается совсем. Прежним правилом
# 174 площадки получили находку «здесь уже продаётся ЖК» — и с нею минус 60%
# балла: «Квартиры от 41 000 руб/м²» доказывало владение 41, а статья про любую
# производственную зону цеплялась к сотне площадок разом (прод, 05.09.2026).
ANCHOR_RULES_VERSION = 7


