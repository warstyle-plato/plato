TOTAL = {"contract": 4_581.84, "paid": 1_691.30, "remain": 2_892.69,
         "sep": 231.85, "oct": 366.94, "sum": 3_024.37}


def book(rows=ROWS, total=TOTAL, unit: str = "") -> bytes:
    from openpyxl import Workbook
    from openpyxl.utils import get_column_letter as col

    wb = Workbook()
    wb.active.title = "ГФ_до конца 2026"   # соседний лист — не он
    ws = wb.create_sheet("ГФ_до конца стр")
    scale = {"": 1.0, "млн": M, "тыс": 1_000.0}[unit]
    ws["A1"] = "График финансирования Кутузов Сити на 23.09.2026" + (
        f", {unit}. руб." if unit else "")
    heads = {1: "Код РСС", 2: "Работа", 3: "Группа ГПР", 4: "Приоритет", 5: "Стадия",
             6: "Статус", 7: "Основание графика", 8: "Нач./макс. сумма договора",
             9: "Разница", 10: "Сумма договора", 11: "Выплачено", 12: "Остаток к выплате",
             13: "Остаток прямого лимита", 31: "Итого", 33: "Резерв",
             34: "Результат на 31.12.2026", 35: "Логика корректировки", 36: "Источник"}
    for c, text in heads.items():
        ws.cell(2, c, text)
    ws["N2"] = "2026 год"
    ws.merge_cells("N2:R2")
    ws["S2"] = "2027 год"
    ws.merge_cells("S2:AD2")
    for offset, name in enumerate(MONTHS_2026 + MONTHS_2027):
        ws.cell(3, 14 + offset, name)
    ws["N4"] = "Скорректированная потребность / оплаты"
    ws.merge_cells("N4:AD4")
    # Тройки «Лимит после / Банк / Резерв» по месяцам — справа, не план.
    for offset, short in enumerate(("авг", "сен", "окт", "ноя", "дек")):
        for part, word in enumerate(("Лимит после", "Банк", "Резерв")):
            ws.cell(3, 38 + offset * 3 + part, f"{word} {short}")
            ws.cell(5, 38 + offset * 3 + part, 999 * M / scale)

    def money(value):
        return value * M / scale if isinstance(value, (int, float)) else value

    r = 5
    for code, work, status, contract, paid, remain, sep, oct_ in rows:
        ws.cell(r, 1, code)
        ws.cell(r, 2, work)
        ws.cell(r, 6, status or None)
        ws.cell(r, 10, money(contract))
        ws.cell(r, 11, money(paid))
        ws.cell(r, 12, money(remain))
        ws.cell(r, 15, money(sep))
        ws.cell(r, 16, money(oct_))
        r += 1
    # Остаток лимита — на родителя с подстроками, объединённой ячейкой.
    for first, last in ((13, 14), (15, 16), (17, 18), (19, 21)):
        ws.cell(first, 13, 50 * M / scale)
        ws.merge_cells(f"M{first}:M{last}")
    ws.cell(r, 2, "ИТОГО")
    ws.cell(r, 10, money(total["contract"]))
    ws.cell(r, 11, money(total["paid"]))
    ws.cell(r, 12, money(total["remain"]))
    ws.cell(r, 15, money(total["sep"]))
    ws.cell(r, 16, money(total["oct"]))
    ws.cell(r, 31, money(total["sum"]))
    ws.cell(r + 1, 2, "Резерв на непредвиденные")
    ws.cell(r + 2, 2, "Резерв на инфляционное")
    ws.cell(r + 4, 2, "Всего:")
    ws.cell(r + 4, 10, money(99_999.0))
    assert col(30) == "AD"
    blob = io.BytesIO()
    wb.save(blob)
    return blob.getvalue()


def rss(payments) -> bytes:
    """РСС с деревом статей графика и реестром платежей: (дата, сумма, код)."""
    from openpyxl import Workbook

    wb = Workbook()
    est = wb.active
    est.title = "Расчет стоимости строительства"
    tree = [("2", "Строительство"), ("2.2", "СМР"), ("2.2.1", "Подземная часть"),
            ("2.2.1.6", "Котлован"), ("2.2.1.7", "Монолит"), ("2.2.1.7.3", "Монолит секции 3"),
            ("2.2.2", "Надземная часть"), ("2.2.2.3", "Кладка"), ("2.2.2.4", "Кровля"),
            ("2.2.2.6", "Фасады"), ("2.2.3", "Инженерные системы"), ("2.2.3.2", "Отопление"),
            ("2.2.3.3", "Водоснабжение"), ("2.2.3.4", "Вентиляция"), ("2.2.3.5", "ЭОМ"),
            ("2.2.3.5.1", "Наружное освещение"), ("2.4", "Благоустройство"),
            ("2.4.4", "Благоустройство двора"), ("2.6", "Служба заказчика"),
            ("3", "Коммерческие расходы"), ("3.1", "Реклама")]
    for offset, (code, name) in enumerate(tree):
        est.cell(10 + offset, 1, code)
        est.cell(10 + offset, 4, name)
        est.cell(10 + offset, 5, 100 * M)
    est.cell(10 + len(tree) + 1, 4, "Всего инвестиционные расходы")
    est.cell(10 + len(tree) + 1, 5, 5_000 * M)
    wb.create_sheet("Реестр договоров")
    paid = wb.create_sheet("Реестр платежей")
    for offset, (day, amount, code) in enumerate(payments):
        row = 10 + offset
        paid.cell(row, 2, "СтройКо")
        paid.cell(row, 3, "Д-1")
        paid.cell(row, 7, code)
        paid.cell(row, 9, day)
        paid.cell(row, 10, amount)
    wb.create_sheet("Реестр выполненных работ")
    blob = io.BytesIO()
    wb.save(blob)
    return blob.getvalue()
