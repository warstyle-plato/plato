"""Ежедневный отчёт из чата стройки читается так, как его пишут на площадке.

Поводом стал живой отчёт с рабочей группы (владелец, 13.09.2026): бот теперь
сидит в чате стройки, куда каждый день уходит численность. Прогон настоящего
текста через разбор нашёл две поломки, и обе видно только на живом формате.

Сам текст владельца в репозиторий не едет: он публичный, а в отчёте настоящие
подрядчики и их численность на живом объекте — это данные проекта, и им место
в `data/` на ядре. Здесь та же ФОРМА с выдуманными именами: «Завоз:» вместо
нашей «Поставки», имя подрядчика внутри строки после нумерованного заголовка,
продолжение работ следующей строкой без разделителя и подрядчик, который
вывел работы и не выводил людей.
"""

from collections import Counter

import developaid_monitor_daily as daily


# Форма живого отчёта: нумерация сбита (нет №4 в численности, две шестёрки в
# работах) — разбор на неё не опирается, и это часть утверждения.
REPORT = """Добрый день.
1. Первый : Итр- 1чел., Рабочие - 6 чел.
2. Второй:ИТР- 11чел.;
Рабочие - 50чел.;
3. Третий ( кладка) - Итр- 2 чел.Рабочие - 11чел.
5. Четвёртый ( отделка) - Итр - 1 чел., Рабочие - 4 чел.
6. Пятый Итр - 3чел., Рабочие- 42 чел.
По работам:
1. Второй:
Корпус 2
Разборка опалубки , вывоз опалубки.
4. Третий( кладка):
Устройство стен из пеноблока и СКЦ
Корпус 3 - 3,4,5,7 эт.
Корпус 1 - 1,3,4,5
6. Пятый -сборка лесов и монтаж люлек на Корпусе 1и2.
Монтаж кранштейнов и стоек на Корпусе 2 и 1.( захватки 1,2,4)
10. Шестой ( теплосети)- монтаж ограждения , армирование плиты.
Завоз:
Блок- 2 маш.
Минвата -1 маш
Вывоз:
Опалубка - 1 маш.
"""


def _by_contractor(works):
    return Counter(item["contractor"] for item in works)


def test_the_delivery_section_is_named_by_the_site_word():
    """«Завоз» — секция, а не подрядчик.

    Разбор знал только «Поставку», и на живом отчёте три строки завоза
    становились контрагентом «Завоз», а поставки оставались пустыми — при том
    что «Вывоз» рядом читался верно. Слово источника, а не наше: ровно та
    ошибка, что уже стоила нам «городских нужд» вместо «Программы реновации».
    """
    parsed = daily.parse_daily_report(REPORT)

    assert parsed["supplies"] == ["Блок- 2 маш.", "Минвата -1 маш"]
    assert parsed["removals"] == ["Опалубка - 1 маш."]
    # Предохранитель: пока «Завоз» был подрядчиком, проверка выше зеленела бы
    # на пустом списке поставок — значит утверждаем и обратное.
    assert "Завоз" not in _by_contractor(parsed["works"])


def test_a_name_inside_the_line_leads_the_lines_that_follow():
    """Имя в строке ведёт и следующие строки — до нового имени или заголовка.

    «Монтаж кранштейнов и стоек…» — продолжение того, кто назван строкой выше
    внутри неё самой, а не работа последнего нумерованного заголовка. На живом
    отчёте из-за этого у одного подрядчика выходило шесть строк вместо
    четырёх, и две из них были чужие.
    """
    parsed = daily.parse_daily_report(REPORT)
    counts = _by_contractor(parsed["works"])

    assert counts["Пятый"] == 2, parsed["works"]
    # Свои три строки остаются у заголовка. Общее число у него больше: туда же
    # падает недоказанное имя — об этом соседняя проверка, и сваливать оба
    # утверждения в одно число значит не проверить ни одного.
    own = [w["line"] for w in parsed["works"] if w["contractor"] == "Третий( кладка)"]
    assert "Устройство стен из пеноблока и СКЦ" in own
    assert "Корпус 3 - 3,4,5,7 эт." in own
    assert "Корпус 1 - 1,3,4,5" in own

    continuation = [w for w in parsed["works"] if w["line"].startswith("Монтаж кранштейнов")]
    assert len(continuation) == 1
    assert continuation[0]["contractor"] == "Пятый"


def test_an_unproven_name_breaks_the_run_instead_of_leading_it():
    """Недоказанное имя обрывает цепочку, а не уводит её за собой.

    «Шестой ( теплосети)- монтаж ограждения» и «Корпус 3 - 3,4,5,7 эт.»
    выглядят одинаково: приставка с разделителем. Первое — настоящий
    подрядчик, который вывел работы и не выводил людей, второе — обычная
    строка работ. Различить их можно только справочником известных имён (его
    даёт маршрут из РСС и реестра ГУ), и пока доказательства нет, строка
    возвращается заголовку. Подписать её задержавшимся именем значило бы
    утверждать то, что мы только что не смогли подтвердить.
    """
    parsed = daily.parse_daily_report(REPORT)
    unproven = [w for w in parsed["works"] if w["line"].startswith("Шестой")]
    assert len(unproven) == 1
    assert unproven[0]["contractor"] != "Пятый", "имя без доказательства увело чужую строку"

    # Со справочником та же строка опознаётся — и это не совпадение имени, а
    # доказательство: сверка та же, что у сверки дня.
    known = ["Первый", "Второй", "Третий", "Четвёртый", "Пятый", "Шестой"]
    fixed = daily.attribute_works(parsed["works"], known)
    named = [w for w in fixed if w["line"].startswith("Шестой")]
    assert named[0]["contractor"] == "Шестой"
    assert named[0].get("named_inline") is True


def test_the_headcount_is_read_and_a_missing_one_is_a_refusal():
    """Численность читается, а её отсутствие — названный отказ, а не ноль людей."""
    parsed = daily.parse_daily_report(REPORT)

    assert [c["name"] for c in parsed["contractors"]][:2] == ["Первый", "Второй"]
    assert parsed["itr_total"] == 18
    assert parsed["workers_total"] == 113

    # Отчёт без численности не превращается в день без людей: `store_daily_report`
    # отказывается и называет причину. Проверяем разбор — на пустом тексте
    # подрядчиков нет вовсе, и вызывающему есть на чём отказать.
    empty = daily.parse_daily_report("Добрый день. Сегодня без сводки.")
    assert empty["contractors"] == []
    assert empty["itr_total"] == 0 and empty["workers_total"] == 0


def test_a_long_line_does_not_hang_the_parser():
    """Строка из чата не должна вешать разбор.

    Секции опознавались шаблонами вида `^\\s*слово\\s*:?\\s*$` — два звёздочных
    пробельных куска подряд у якоря конца строки. На «поставка» с 60 000
    пробелов и одним лишним знаком такой шаблон считается 14,17 секунды
    (замерено 13.09.2026), и растёт он квадратично. Пока текст приходил
    загрузкой из кабинета, это было теоретическим; с того дня его пишет кто
    угодно в групповом чате — то есть одно сообщение вешало воркер бота.
    CodeQL назвал ровно эти три места, и назвал верно.

    Порог здесь с большим запасом: разница между прежним и нынешним — четыре
    порядка, и секунда отделяет «линейно» от «перебор», а не меряет машину.
    """
    import time

    evil = "поставка" + " " * 60000 + "x"
    started = time.perf_counter()
    parsed = daily.parse_daily_report(evil)
    spent = time.perf_counter() - started

    assert spent < 1.0, f"разбор занял {spent:.2f} с — шаблон снова уходит в перебор"
    # И заодно: такая строка секцией не становится — «поставка» с хвостом это
    # не заголовок «Поставка:».
    assert parsed["supplies"] == []
