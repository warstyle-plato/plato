"""Номер владения доказывается адресом, а не любым числом в тексте.

«Что-то рейтинги как было левые так и остались» (владелец, 05.09.2026).
Измерено на проде настоящей функцией страницы: из 580 строк каталога 355
стояли «Низкое», медиана балла 19. Самое частое снижение — минус 60% за
находку «на площадке уже продаётся ЖК»: она стояла у 174 площадок, 131 из них
— площадки-решения, где ЖК не может продаваться по построению (проект решения
публикуют ДО того, как что-либо решено).

Причин две, и обе про доказательство.

**Число считалось номером владения где угодно в тексте.** Адресная позиция
требовалась только от ОДНОЙ цифры, а двузначное число проходило само по себе:
«Квартиры от 41 000 руб/м²» доказывало владение 41 на Талалихина, и страница
продаж чужого ЖК становилась находкой. Так у Талалихина, вл. 41 в находках
оказались «ЖК ВернадSKY» и «Квартал Мит», а у площадки в пос. Щапово — «ЖК
Акварель» с томского домена.

**Якорь из общего слова опознавал квартал, а не площадку.** У имён
площадок-решений это не улица: якорь «произ» (производственной) стоял у 114
площадок разом, «зоне» — у 112. Любая статья про производственную зону
цеплялась ко всем.

Правило то же, что уже записано про одинокую цифру и про улицу, — здесь оно
доведено до конца: **число становится номером владения только в адресной
позиции**, а **якорь, общий с соседней площадкой, у площадки без номера не
работает вовсе**.

Запуск: python3 -m pytest tests/test_a_price_is_not_a_house_number.py -q
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from market_search import krt_open_sources as sources  # noqa: E402


def _ours(text: str, site: str) -> bool:
    """Назван ли в тексте номер владения НАШЕЙ площадки."""
    return sources._says_our_number(
        text, sources._house_numbers(site), sources._anchor_words(site))


SITE = "Талалихина ул., вл. 41"


def test_a_price_does_not_prove_our_address() -> None:
    """Число в цене, в площади и в номере корпуса — не номер владения."""
    assert not _ours("Квартиры от 41 000 руб/м² в новом доме", SITE)
    assert not _ours("Старт продаж ЖК «Квартал Мит», корпус 41", SITE)
    assert not _ours("ЖК ВернадSKY от застройщика Илион-Трейд — купить квартиру", SITE)
    assert not _ours("41 квартира продана за месяц", SITE)


def test_the_address_position_still_proves_it() -> None:
    """Чинить правило отключением нельзя: настоящий адрес по-прежнему считается.

    Три записи, все живые: с сокращением, без него и одним именем улицы —
    «ЖК Талалихина, 41» публикация пишет именно так.
    """
    assert _ours("Работы по адресу: Талалихина ул., вл. 41", SITE)
    assert _ours("ЖК Талалихина, 41 | Старт продаж ЖК бизнес-класса", SITE)
    assert _ours("ЖК от STONE на Светлый проезд, 4 — старт продаж",
                 "Светлый проезд, вл. 4")
    # Диапазон покрывает свои концы — находка владельца от 03.09.2026.
    assert _ours("на Озерной улице, 42-46 построят жильё", "Озерная ул., вл. 42-46")


def test_a_word_shared_with_a_neighbour_is_not_an_anchor() -> None:
    """Общее слово опознаёт квартал: у площадки без номера оно снимается.

    Имена сняты с живого каталога 05.09.2026 — там таких «производственных зон»
    больше сотни, и якорь у них выходил один на всех.
    """
    siblings = ["в производственной зоне № 49 «Бескудниково»",
                "в производственной зоне № 51 «Медведково»",
                "в производственной зоне №31 «Кашира»"]
    anchors, phrase = sources.usable_anchors(siblings[0], siblings)
    assert "произ" not in anchors, anchors
    assert "зоне" not in anchors, anchors
    # Собственное имя площадки остаётся: им она и опознаётся.
    # Основа берётся пятью буквами — «Бескудниково» даёт «беску».
    assert "беску" in anchors, anchors

    # У площадки С номером владения общее слово остаётся рабочим: там строгий
    # режим требует наш номер в предложении, и терять улицу незачем.
    with_house = "Варшавское ш., вл. 37"
    kept, _ = sources.usable_anchors(with_house, ["Варшавское ш., вл. 61А/1"])
    assert any(stem.startswith("варша") for stem in kept), kept


def test_the_brand_is_taken_by_the_same_anchors() -> None:
    """Бренд вынимается тем же набором якорей, что и находки.

    Пока бренд брался по сырым якорям, отсев общего слова ничего не менял:
    имя ЖК с чужой статьи всё равно становилось вторым якорем и открывало
    дорогу всей странице.
    """
    source = (Path(__file__).resolve().parents[1]
              / "market_search" / "krt_open_sources.py").read_text(encoding="utf-8")
    start = source.index("def brand_names(")
    body = source[start:source.index("\ndef ", start + 10)]
    assert "usable_anchors(name, siblings)" in body, body[:400]
    assert "_site_anchor(name)" not in body, "бренд берётся по сырым якорям"


def test_the_rules_version_grew() -> None:
    """Находки прежнего правила признаком не считаются до перечитывания.

    Это и есть починка на проде: 458 строк рейтинга посчитаны версией 6, и с
    подъёмом версии их находки перестают снижать балл — до одного нажатия
    «Прочитать публикации», а не после него.
    """
    assert sources.ANCHOR_RULES_VERSION >= 7
