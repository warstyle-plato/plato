"""Плашка обещает погашение продажами — число, отвечающее «погасился ли», рядом.

«Эскроу не погашает ПФ полностью… остаток должен быть погашен последующими
продажами» — и всё. Проверить обещание на экране было нечем: непогашенный долг
на конец проекта стоял только в PDF и на листе ОТЧЁТ книги, а на странице его
не было вовсе (владелец, 25.08.2026: «а где эта строка? её нет»).

Вторая половина того же экрана: три числа плашки не вычитались. 107,75 млрд
долга перед раскрытием минус 106,2 раскрытого эскроу даёт 1,55, а показано было
7,73. Ошибки в счёте нет — эскроу гасит СВОЙ ПФ, а излишек уходит в кассу
проекта: у одной очереди раскрытого больше её долга, у другой меньше, и в своде
они складываются. Значит на строке не хватало четвёртого числа — сколько из
раскрытого пошло на погашение.

Запуск: python3 -m pytest tests/test_the_screen_answers_its_own_warning.py -q
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import main_legacy as core  # noqa: E402


def test_the_engine_reports_what_the_escrow_actually_repaid() -> None:
    """Раскрытое и погашенное — разные величины, и у второй есть имя."""
    source = Path(core.__file__).read_text(encoding="utf-8")
    assert '"rve_pf_repayment": rve_pf_repayment,' in source
    assert '"rve_pf_repayment": sum(f.get("rve_pf_repayment", 0.0) for f in fs),' in source


def test_the_screen_shows_the_ending_debt() -> None:
    """Строка, ради которой плашка и написана."""
    assert "Непогашенный долг ПФ на конец проекта" in core.PAGE
    assert "r.report.financing.ending_pf" in core.PAGE


def test_all_four_numbers_are_on_the_screen() -> None:
    """Раскрыто, погашено, остаток, конец — все четыре на экране.

    Требование родилось из счёта, который не сходился: 107,75 млрд долга минус
    106,2 раскрытого эскроу даёт 1,55, а показано было 7,73. Ошибки не было —
    эскроу гасит СВОЙ ПФ, излишек уходит в кассу, — не хватало четвёртого
    числа: сколько из раскрытого пошло на погашение.

    С 30.08.2026 числа живут не в плашке, а в карточке финансирования: плашка
    стала рассказом по очередям («невнятный текст» — владелец), и четыре
    величины в одной фразе вернули бы ей ту самую невнятность. Требование от
    этого не исчезло — проверять его надо там, где числа теперь стоят.
    """
    for label in ("Раскрытый эскроу в РВЭ", "Из него на погашение ПФ",
                  "Остаток ПФ после раскрытия в РВЭ",
                  "Непогашенный долг ПФ на конец проекта"):
        assert label in core.PAGE, label
    assert "rve_pf_repayment" in core.PAGE


def test_the_two_outcomes_are_said_in_different_words() -> None:
    """Ноль на конец и остаток — разные исходы, и сказаны они по-разному.

    Слова с 30.08.2026 другие: дефолт называется дефолтом с датой и суммой, а
    благополучный исход — «долг погашен полностью», и рядом оговорка, что план
    держится на согласии банка.
    """
    page = core.PAGE
    assert "по модели это <b>дефолт" in page
    assert "долг погашен полностью" in page
    assert "Понадобится согласие банка" in page
    # Прежняя мягкая формулировка снята: банк не ждёт продаж.
    assert "Остаток гасится продажами после ввода" not in page
