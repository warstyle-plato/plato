"""Застройщик построенного дома — не застройщик площадки КРТ по тому же адресу.

«Почему опять это фск и почему тогда уж не занята» (владелец, 04.09.2026).
Снято со строк прода: у Варшавского ш., вл. 37 в находках стояла «ГК ФСК» с
цитатами «ЖК „Роттердам“ акции от официального застройщика» (cian) и «ЖК
„Роттердам“ от застройщика ГК ФСК — 25 квартир по цене от…» (realty.yandex).
Ни в одной из них нет ни слова о КРТ: это страницы продаж ПОСТРОЕННОГО дома по
адресу «Варшавское шоссе, 37», а у нас ВЛАДЕНИЕ 37 — номер один, объект другой.

И та же пара страниц была засчитана ВТОРОЙ площадке — «Варшавское ш., вл.
61А/1»: её номера дают ещё и одинокую «1», а одинокая цифра совпадает с чем
угодно.

Правило: утверждение «вот кто здесь будет строить» доказывается документом ПРО
КРТ. Отсюда же ответ на вторую половину вопроса: имя застройщика вход не
закрывает (методика владельца 03.09.2026) — и метка теперь говорит это сама,
иначе строка показывает имя и не показывает занятости, то есть два ответа на
один вопрос.

Запуск: python3 -m pytest tests/test_a_sales_page_does_not_name_our_builder.py -q
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from auction_search import ui  # noqa: E402
from market_search import krt_open_sources as sources  # noqa: E402


class Doc:
    def __init__(self, title: str, snippet: str, url: str) -> None:
        self.title, self.snippet, self.url = title, snippet, url


# Живые документы. Цитаты и ссылки — те самые, что лежат в строках прода
# (`press_facts.developer_named`); заголовок выдумывать нельзя, поэтому он
# взят той же фразой: проверяем ровно то, что измерено.
# Витрина при этом НЕ доказала, что продаёт на нашей площадке: в строке прода
# корзина «здесь уже продаётся ЖК» пуста, а застройщик стоит. Значит связь с
# площадкой держалась не на адресе, а на имени ЖК — «Роттердам» становился
# вторым якорем и открывал странице всю дорогу. Чужой номер в документе
# (офис продаж по соседнему дому) воспроизводит ровно этот исход.
SALES = [
    Doc("ЖК «Роттердам» акции от официального застройщика ГК ФСК",
        "ЖК «Роттердам» акции от официального застройщика ГК ФСК. "
        "25 квартир от застройщика в ЖК «Роттердам» на Варшавском шоссе. "
        "Офис продаж: Варшавское шоссе, д. 39, к. 1.",
        "https://zhk-rotterdam-i.cian.ru/"),
    Doc("ЖК «Роттердам» от застройщика ГК ФСК",
        "ЖК «Роттердам» от застройщика ГК ФСК — 25 квартир по цене от 12 млн "
        "на Варшавском шоссе. Офис продаж: Варшавское шоссе, д. 39, к. 1.",
        "https://realty.yandex.ru/moskva_i_moskovskaya_oblast/kupit/novostrojka/rotterdam-2756197/"),
]
ABOUT_KRT = [
    Doc("Оператором КРТ на Варшавском шоссе, вл. 37 стала компания «Пример»",
        "Проект комплексного развития территории на Варшавском шоссе, вл. 37 "
        "реализует ГК «Пример».",
        "https://www.mos.ru/news/item/1"),
]
OURS = "Варшавское шоссе, вл. 37, Нагатинская ул., влд. 3А/6"
NEIGHBOUR = "Варшавское ш., вл. 61А/1; Нагатинская ул., вл. 29, к. 4"


def test_a_sales_page_gives_no_builder() -> None:
    found = sources.read_findings(SALES, OURS, [NEIGHBOUR])
    assert found["developer_named"] == [], \
        "застройщик построенного дома приписан площадке КРТ по тому же номеру"
    assert found["operator_named"] == []


def test_the_same_page_is_not_given_to_the_neighbour_either() -> None:
    """Одинокая цифра из «61А/1» ловила ту же страницу второй площадке."""
    found = sources.read_findings(SALES, NEIGHBOUR, [OURS])
    assert found["developer_named"] == [], "одинокая «1» опознала чужой документ"


def test_a_publication_about_krt_still_names_the_operator() -> None:
    """Строгость не должна съесть настоящую находку."""
    found = sources.read_findings(ABOUT_KRT, OURS, [NEIGHBOUR])
    assert [item["name"] for item in found["operator_named"]] == ["Пример"]
    assert found["taken"] is True, "названный оператор вход закрывает"


def test_a_lone_digit_counts_only_in_an_address_position() -> None:
    """«на Светлый проезд, 4» — адрес; «25 квартир по цене от 1 млн» — нет.

    Одинокая цифра совпадает с чем угодно, поэтому она считается номером
    только сразу после названия улицы или указателя владения. Резать её
    целиком было нельзя: «Светлый проезд, 4» — живая находка владельца.
    """
    from market_search.krt_open_sources import _says_our_number

    assert _says_our_number("ЖК от STONE на Светлый проезд, 4 — старт продаж", {"4"}), \
        "адрес без сокращения перестал опознаваться — потеряли настоящую находку"
    assert _says_our_number("Оператором КРТ на Проектируемом проезде, вл. 1 стала ГК", {"1"})
    assert not _says_our_number(
        "ЖК «Роттердам» от застройщика ГК ФСК — 25 квартир по цене от 1 млн", {"1"}), \
        "одинокая цифра снова ловит что угодно"


def test_the_selling_bucket_is_left_to_the_owner() -> None:
    """Здесь мы НЕ трогаем «на площадке уже продаётся ЖК».

    Та же пара страниц может поднять и эту метку: доказательство ей — наш
    номер владения в документе, а страница продаж его называет. Отличить
    «Страна.Озерная строится НА нашей площадке» (там метка верна, владелец
    03.09.2026) от «ЖК Роттердам достроен по соседству» в тексте нечем — это
    вопрос методики, а не разбора, и он записан открытым. Тест держит границу:
    правка сняла имя застройщика и продаж не касалась.
    """
    assert any(bucket["key"] == "selling_now" and bucket["heavy"]
               for bucket in sources.FINDING_BUCKETS), \
        "корзина продаж пропала или перестала закрывать вход — это другое решение"


def test_the_rules_version_grew() -> None:
    """Прежние находки посчитаны прежним правилом — их надо перечитать."""
    assert sources.ANCHOR_RULES_VERSION >= 6


def test_the_tag_says_it_does_not_close_the_entry() -> None:
    """«Почему тогда уж не занята» — метка обязана отвечать сама."""
    page = ui.auctions_page()
    assert "не оператор КРТ" in page and "вход это само по себе не закрывает" in page.lower(), \
        "имя застройщика стоит без веса — строка показывает два ответа на один вопрос"
