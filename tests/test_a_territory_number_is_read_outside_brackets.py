"""Номер части площадки читается отовсюду, а не только из скобок.

«А где проект решения?» — владелец, 20.09.2026, карточка «Дербеневская ул.
тер. 2». Документ на mos.ru есть, в нашем снимке он тоже есть — «ул.
Дербеневская (территория 2)», — а к карточке привязан не был: уточнение город
пишет в скобках в решении и без скобок в каталоге, и пустая сторона пары с
непустой не спорит.

Замер прода того же дня (579 решений × 282 карточки каталога): привязок было
293, стало 299. Девять снятых — это конфликт номеров, то есть привязки НЕВЕРНЫЕ
(«Соколиная гора (территория 2)» стояла на карточке «тер. 1», «Серп и Молот
(территория № 3)» и «(№ 4)» — там же); четыре решения переехали на свою
карточку; пятнадцать нашли её впервые. Правило приёмки прежнее: сопоставление
проверяют не на том, что оно НАШЛО, а на том, что оно нашло ВЕРНО.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from market_search.krt_decisions import (  # noqa: E402
    named, part_numbers, qualifier, same_place,
)


def test_the_number_is_read_in_every_spelling() -> None:
    """Город пишет одно и то же пятью способами — читаются все."""
    for line in ("ул. Дербеневская (территория 2)", "Дербеневская ул. тер. 2",
                 "Дербеневская ул., территория № 2", "тер.2 Дербеневская"):
        assert part_numbers(line, "территория") == frozenset({"2"}), line
    assert part_numbers("Магистральные улицы тер. 4, 5, 6", "территория") \
        == frozenset({"4", "5", "6"}), \
        "номера идут списком — часть, выданная за целое, читается как целое"
    assert part_numbers("Бескудниково (территории 1, 2)", "территория") \
        == frozenset({"1", "2"})
    assert part_numbers("Хапиловка тер. 1 (проект 2.1)", "проект") \
        == frozenset({"2.1"}), "проект 2.1 и проект 2 — разные части"
    assert part_numbers("Хапиловка тер. 1 (проект 2.1)", "территория") \
        == frozenset({"1"}), "две величины в одной строке не путаются"


def test_the_card_and_the_decision_are_the_same_place() -> None:
    """Живая пара с прода: карточка каталога и её проект решения."""
    assert same_place("ул. Дербеневская (территория 2)", "Дербеневская ул. тер. 2")
    assert same_place("ул. Дербеневская (территория 1)", "Дербеневская ул. тер. 1")
    assert not same_place("ул. Дербеневская (территория 1)", "Дербеневская ул. тер. 2"), \
        "соседняя территория той же улицы — другая площадка"


def test_a_conflicting_number_refuses_the_pair() -> None:
    """Девять привязок прода были неверны ровно этим — и сняты."""
    assert not same_place(
        "в производственной зоне № 22 «Соколиная гора» (территория 2, проект 2)",
        "Соколиная гора тер. 1")
    assert not same_place(
        "в производственной зоне № 23 «Серп и Молот» (территория № 3)",
        "Серп и Молот тер. 1 + 2-я Синичкина улица, вл. 4")
    assert same_place("в производственной зоне № 23 «Серп и молот» (территория 2)",
                      "Серп и Молот тер. 2"), \
        "та же строка обязана найти СВОЮ карточку, иначе снятие — потеря"


def test_the_number_alone_does_not_name_the_site() -> None:
    """Совпавший номер части — признак сильный, но площадку он не опознаёт."""
    assert not same_place(
        "в производственной зоне № 37а «Южное Очаково» (территория 3)",
        "Северное Очаково тер. 3 (проект 1)"), \
        "различающее слово улицы у сторон разное — это разные площадки"
    assert not same_place(
        "в производственной зоне № 56 «Грайвороново» (район Рязанский, территория 2)",
        "Карачарово тер. 2, район Нижегородский"), \
        "общий район и общий номер — не имя: зоны разные"
    assert named("в производственной зоне № 56 «Грайвороново» (район Рязанский)") \
        == frozenset({"грайвороново"})
    assert same_place("в производственной зоне № 54 «Прожектор» (территория 1), р-н Перово",
                      "КРТ Прожектор (территория 1)"), \
        "имя в кавычках отозвалось в словах карточки — это она"


def test_the_okrug_in_brackets_is_not_a_part_of_the_site() -> None:
    """«(САО, ЦАО)» — округа, а не часть площадки, и спорить ими нельзя."""
    assert qualifier("Магистральные улицы (территория № 4, 5, 6) (САО, ЦАО)") \
        == frozenset({"сао", "цао"}), "номер части в остаток скобок не входит"
    assert same_place(
        "в производственной зоне № 5 «Магистральные улицы» (территория № 4, 5, 6) (САО, ЦАО)",
        "Магистральные улицы тер. 4, 5, 6")
    assert same_place("в производственной зоне № 50 «Алтуфьевское шоссе» (проект 2, территория 1)",
                      "Алтуфьевское шоссе тер. 1 (проект 2)"), \
        "где город написал номер — в скобках или рядом — площадку не меняет"
