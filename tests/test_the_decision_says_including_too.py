"""Части объёма город открывает и словом «включая», и перечнем из двух строк.

Владелец о карточке «ул. Архитектора Власова, влд. 59»: «по Власова в модель
жилье почему-то вообще не передаётся, хотя выше мы прекрасно видим сколько там
квартир». Карточка показывала «Жилое назначение 0 м²» при общем объёме 27 915 м²
и предупреждении «слагаемые дают 3 789 м² — разница 24 126 м²».

Решение называет всё прямым текстом:

    Предельная (максимальная) суммарная поэтажная площадь объектов
    капитального строительства в габаритах наружных стен – 27 915 кв. м,
    включая:
    - объекты жилого назначения – 26 260 кв. м;
    - объекты общественно-делового и иного назначения – 1 655 кв. м.

Не читалось по двум причинам сразу: слово перечня разбор знал одно («в том
числе»), а `_clause` кончает фразу на первой точке с запятой — то есть на
первой же части перечня. Замер прода 22.09.2026: 20 строк-решений из 240,
2,42 млн м² общего объёма, 0,98 млн м² квартир прочитаны при пустом жилье.

Запуск: python3 -m pytest tests/test_the_decision_says_including_too.py -q
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from market_search import krt_decision_tep as tep  # noqa: E402

# Настоящий текст решения по Власова, влд. 59 (документ mos.ru 349135220).
VLASOV = """
1. Установить, что комплексному развитию подлежит территория нежилой застройки
города Москвы площадью 3,66 га, расположенная по адресу: г. Москва,
ул. Архитектора Власова, влд. 59.
Предельная (максимальная) суммарная поэтажная площадь объектов капитального
строительства в габаритах наружных стен – 27 915 кв. м, включая:
- объекты жилого назначения – 26 260 кв. м;
- объекты общественно-делового и иного назначения – 1 655 кв. м.
Предельная (минимальная) суммарная поэтажная площадь объектов капитального
строительства общественно-делового и иного назначения – 1 241,25 кв. м.
Предельная (максимальная) площадь квартир – 15 681 кв. м.
Предельная (максимальная) нежилая наземная площадь – 3 410 кв. м.
"""


def test_the_parts_after_including_are_read_and_they_close_the_total() -> None:
    """Сумма названных частей обязана сойтись с названным целым."""
    out = tep.parse(VLASOV)
    assert out["area_ha"] == 3.66
    assert out["total_gfa_sqm"] == 27915.0
    assert out["housing_gfa_sqm"] == 26260.0, "жилое назначение названо документом"
    assert out["nonresidential_gfa_sqm"] == 1655.0, "вторая часть перечня — тоже часть"
    assert out["flats_sqm"] == 15681.0
    assert out["nonresidential_ground_sqm"] == 3410.0
    # Главная приёмка: город сам свёл слагаемые с целым, и мы это повторяем.
    assert out["housing_gfa_sqm"] + out["nonresidential_gfa_sqm"] == out["total_gfa_sqm"]
    # Части целое не удваивают: 27 915 — это ОНО, а не оно плюс части.
    assert out["parts"]["spp_unnamed"] == 1
    assert out["parts"]["inner_housing"] == 1 and out["parts"]["inner_nonres"] == 1


def test_the_older_wording_still_reads() -> None:
    """«В том числе» из одной части — как читалось на Большом Тишинском."""
    out = tep.parse(
        "Предельная (максимальная) суммарная поэтажная площадь объектов "
        "капитального строительства – 9 800 кв. м, в том числе объектов "
        "жилого назначения – 9 800 кв. м.")
    assert out["total_gfa_sqm"] == 9800.0
    assert out["housing_gfa_sqm"] == 9800.0


def test_a_semicolon_between_sentences_still_ends_the_clause() -> None:
    """Предохранитель: точка с запятой РАЗДЕЛЯЕТ части только внутри перечня.

    Без перечня она по-прежнему кончает формулу, и соседнее число в неё не
    затягивается — иначе «нежилая наземная» приехала бы жилым объёмом.
    """
    out = tep.parse(
        "Предельная (максимальная) суммарная поэтажная площадь – 10 000 кв. м; "
        "объекты жилого назначения – 40 000 кв. м.")
    assert out["total_gfa_sqm"] == 10000.0
    assert out["housing_gfa_sqm"] is None, "части перечня не объявлены — их и нет"


def test_an_unnamed_part_is_skipped_and_not_guessed() -> None:
    """Часть без назначения не приписывается ни жилью, ни нежилому."""
    out = tep.parse(
        "Предельная (максимальная) суммарная поэтажная площадь – 30 000 кв. м, "
        "включая: - объекты жилого назначения – 20 000 кв. м; "
        "- прочие объекты – 10 000 кв. м.")
    assert out["total_gfa_sqm"] == 30000.0
    assert out["housing_gfa_sqm"] == 20000.0
    assert out["nonresidential_gfa_sqm"] is None
    # Расхождение не спрятано: сумма частей меньше целого, и это видно.
    assert out["housing_gfa_sqm"] < out["total_gfa_sqm"]


def test_a_document_without_the_figure_says_none_not_zero() -> None:
    """Не назвал документ — `None`. Ноль был бы утверждением города."""
    out = tep.parse("Предельная (максимальная) площадь квартир – 15 681 кв. м.")
    assert out["flats_sqm"] == 15681.0
    assert out["housing_gfa_sqm"] is None and out["total_gfa_sqm"] is None
