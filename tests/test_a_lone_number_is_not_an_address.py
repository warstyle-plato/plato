"""Голая цифра адресом не является — иначе контур приезжает чужой.

Проверено на проде 05.09.2026: карточка площадки «Большой Тишинский пер.,
влд. 8, стр. 1,2» (проект решения 347614220) показывала контур с подписью
«официальный полигон границ» — и полигон этот стоял в Зеленограде, в 28 км,
у площадки «Генерала Алексеева пр-т, вл. 46, стр. 2, 4801 пр-д, вл. 4,
стр. 1, 2».

Причина в разборе составного имени. «стр. 1, 2» — это ОДНО владение с двумя
строениями, а разбор резал по запятым и делал из «2» отдельную часть адреса;
любая площадка, в имени которой тоже нашлась часть «2», совпадала. На живом
файле карты таких имён семь, и через них ошибочно сцепились одиннадцать
площадок-решений из пятнадцати совпавших по адресу.

Та же ошибка уже ловилась в разборе публикаций («одинокая цифра ловила что
угодно», 04.09.2026) — здесь она в другом модуле и с худшим исходом: чужой
контур выдаётся за официальный полигон города.

Мера на снимке прода 05.09.2026 (265 площадок файла карты, 295
площадок-решений с адресом): совпадений по адресу было 15, из них верных 4;
стало 4 — ровно верные. Каталог при этом не двинулся: 225 по имени, 4 по
адресу, 53 без совпадения до и после.

Запуск: python3 -m pytest tests/test_a_lone_number_is_not_an_address.py -q
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from market_search.krt_registry import _address_parts, _map_match  # noqa: E402

# Имена сняты с живого файла карты и списка решений 05.09.2026.
_SITES = [
    {"slug": "generala-alekseeva", "district": "Матушкино",
     "name": "Генерала Алексеева пр-т, вл. 46, стр. 2, 4801 пр-д, вл. 4, стр. 1, 2"},
    {"slug": "magistralnye", "district": "Хорошёвский",
     "name": "Магистральные улицы тер. 4, 5, 6"},
    {"slug": "kronshtadtsky", "district": "Головинский",
     "name": "Кронштадтский бульвар, вл. 47"},
    {"slug": "firsanovskoe", "district": "Савёлки",
     "name": "Фирсановское ш., вл. 15-19"},
    {"slug": "varshavskoe-37", "district": "Нагатино-Садовники",
     "name": "Варшавское шоссе, вл. 37, Нагатинская ул., влд. 3А/6"},
]


def test_a_building_number_does_not_start_a_new_address() -> None:
    """«стр. 1, 2» — одно владение, а не адрес и цифра рядом."""
    assert _address_parts("Большой Тишинский пер., влд. 8, стр. 1,2") == [
        "большой тишинский пер вл 8 стр 1 2"]
    assert _address_parts("Маршала Жукова пр-т, вл. 4, 6") == [
        "маршала жукова пр т вл 4 6"]
    # Часть без названия места ключом не работает: «№17» — это номер, а не
    # адрес, и совпадение по нему было бы совпадением по букве.
    assert _address_parts("№17, 18 Вагоноремонт") == ["18 вагоноремонт"]
    # Настоящее составное имя по-прежнему разбирается на адреса — ради этого
    # правило и писалось (Варшавское ш., вл. 37, владелец 03.09.2026).
    assert _address_parts("Варшавское шоссе, вл. 37, Нагатинская ул., влд. 3А/6") == [
        "варшавское ш вл 37", "нагатинская ул вл 3а 6"]


def test_the_map_does_not_hand_over_a_neighbours_polygon() -> None:
    """Чужой контур не выдаётся за официальный полигон площадки."""
    wrong = _map_match(_SITES, "decision:347614220",
                       "Большой Тишинский пер., влд. 8, стр. 1,2")
    assert wrong["site"] is None, wrong
    assert "нет в файле карты" in wrong["problem"], wrong

    # И у соседних жалоб того же снимка: Берзарина и Тверская сцеплялись с
    # «Магистральными улицами» через «4» и «5».
    for name in ("Берзарина ул., влд. 28, стр. 3, 4, 5",
                 "ул. Тверская, влд. 20/1, стр. 1, 4, 5"):
        assert _map_match(_SITES, "x", name)["site"] is None, name


def test_the_same_place_written_differently_still_matches() -> None:
    """Правило чинится не отключением: настоящий адрес по-прежнему находится."""
    same = _map_match(_SITES, "decision:1", "Кронштадтский б-р, вл. 47")
    assert (same["site"] or {}).get("slug") == "kronshtadtsky", same
    assert same["matched"] == "address"

    zelenograd = _map_match(_SITES, "decision:2", "г. Зеленоград, Фирсановское ш., влд. 15-19")
    assert (zelenograd["site"] or {}).get("slug") == "firsanovskoe", zelenograd

    # Составное имя площадки каталога находит себя по каждому своему адресу.
    part = _map_match(_SITES, "decision:3", "Варшавское ш., вл. 37")
    assert (part["site"] or {}).get("slug") == "varshavskoe-37", part


def test_every_site_of_the_file_finds_itself() -> None:
    """Строгость не должна отрезать площадку от её собственной записи.

    На живом файле это проверено целиком: 265 из 265 находят себя по имени.
    """
    for site in _SITES:
        found = _map_match(_SITES, "нет-такого-слага", site["name"])
        assert (found["site"] or {}).get("slug") == site["slug"], site["name"]
