"""Балл лота — соответствие девелоперскому профилю, а не догадка о продаже.

«Баллы это соответствие девелоперскому профилю»; «сделки — это бенчмарк 100
соответствия» (владелец, 26.08.2026). Эталон — не наше представление о хорошем
лоте, а то, что владелец покупал на самом деле: 121 сделка 2025 года с
площадью, ценой и удельной ценой по каждой.

Отсюда два следствия, оба важнее самой формулы.

Первое: **эталон измерен, а не назначен.** Числа ниже сняты с файла сделок
один раз, названы вместе с источником и объёмом выборки и живут одной
константой. Порог, взятый на глаз, на экране выглядит ровно так же уверенно,
как измеренный.

Второе, и его я сначала прочитал неверно: **эталон задаёт нижнюю границу, а не
коридор.** Сделки 2025 года мельче предложения — медиана участка 2 956 м²
против 28 506 в реестре, — но это про то, что тогда предлагали, а не про то,
что нужно. «Крупнее лучше! просто тогда таких сделок не было» (владелец,
26.08.2026). Поэтому сверху штрафа нет вовсе: лот, вышедший за девять десятых
прошлых сделок, — не «мимо профиля», а крупнее всего, что попадалось. Мимо
профиля бывает только снизу: гараж на сотке за двести тысяч не площадка ни при
каком рынке.

Прежний порог «меньше 500 м² — не площадка» при этом стоял там, где у
владельца лежит четверть его сделок: четверть их — участки до 1 109 м².
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

# Откуда числа. Стоит рядом с ними, потому что вопрос «почему именно столько»
# возникает первым, а искать ответ в переписке — значит его не найти.
BENCHMARK_SOURCE = "121 сделка владельца за 2025 год (файл «ИТОГИ ДЕВЕЛОПМЕНТ 2025»)"


@dataclass(frozen=True)
class Band:
    """Полоса эталона: где лежат десятая, четвертьная, средняя и остальные доли.

    Соответствие считается по этим точкам, а не по «больше — лучше»: у каждой
    величины есть и слишком мало, и слишком много.
    """
    name: str
    unit: str
    p10: float
    p25: float
    median: float
    p75: float
    p90: float
    measured: int


# Снято с файла сделок 26.08.2026. Площадь участка заполнена не у всех сделок
# (71 из 121) — это «не записано», а не «земли не было», поэтому объём выборки
# у каждой полосы свой и назван.
LAND = Band("участок", "м²", 434, 1_109, 2_956, 11_967, 45_125, 71)
BUILDING = Band("строения", "м²", 393, 615, 1_351, 3_608, 11_036, 121)
PRICE = Band("цена", "₽", 48_296_550, 97_216_000, 204_834_000, 458_363_298, 930_600_000, 121)
PER_SQM = Band("цена за м² строений", "₽/м²", 46_613, 79_740, 139_070, 222_247, 342_961, 121)


def _place(value: float | None, band: Band) -> tuple[float, str]:
    """Насколько величина похожа на сделку: доля от 0 до 1 и объяснение.

    Граница односторонняя: снизу. Лестница вниз пологая намеренно — лот чуть
    мельче десятой части сделок всё ещё такая сделка, а мельче в пятнадцать
    раз — другой предмет. Резкая ступень означала бы, что 393 м² это профиль,
    а 390 м² — нет.

    Насколько именно мимо, сказано числом: «в пятнадцать раз ниже» объясняет
    больше, чем «мало».
    """
    if value is None or value <= 0:
        return (0.0, "")
    if value >= band.p25:
        # Сверху границы нет: крупнее — лучше, и «выше девяти десятых прошлых
        # сделок» означает только, что таких тогда не предлагали.
        return (1.0, "")
    if value >= band.p10:
        return (0.85, "")
    times = band.p10 / value
    if times <= 1.5:
        # Полшага ниже края — это край, а не другой предмет.
        return (0.7, "")
    share = 0.4 if times <= 3 else (0.15 if times <= 8 else 0.0)
    return (share,
            f"{band.name} {_short(value, band.unit)} — ниже десятой части сделок "
            f"({_short(band.p10, band.unit)}) в {_times(times)}")


def _times(value: float) -> str:
    """«в 1,7 раза», «в 15 раз» — по-русски, а не «в 2 раз(а)»."""
    if value < 10:
        # У дробного числа существительное всегда в родительном единственного:
        # «в 6,1 раза», а не «в 6,1 раз».
        return f"{value:.1f}".replace(".", ",") + " раза"
    number = int(round(value))
    last = number % 10
    if number % 100 in range(11, 15) or last in (0, 5, 6, 7, 8, 9):
        word = "раз"
    else:
        word = "раза" if last in (2, 3, 4) else "раз"
    return f"{number} {word}"


def _short(value: float, unit: str) -> str:
    if unit == "₽":
        # Мелкая сумма, округлённая до миллионов, превращается в ноль, и «цена
        # 0 млн ₽» читается как отсутствие цены, а не как двести тысяч.
        if value < 10e6:
            return f"{value / 1e6:.1f} млн ₽".replace(".", ",")
        return f"{value / 1e6:,.0f} млн ₽".replace(",", " ")
    return f"{value:,.0f} {unit}".replace(",", " ")


def profile_fit(lot: dict[str, Any]) -> dict[str, Any]:
    """Соответствие лота профилю сделок: доля, объяснение и что не измерено.

    Считается ЗДЕСЬ, а не на экране: балл, собранный в браузере, был бы вторым
    счётом той же величины, и разойдись он с этим — оба выглядели бы верными.
    """
    land = _number(lot.get("land_area_sqm"))
    building = _number(lot.get("building_area_sqm"))
    price = _number(lot.get("current_price_rub"))
    if price is None:
        price = _number(lot.get("start_price_rub"))
    per_sqm = price / building if price and building else None

    # Удельная цена в соответствие НЕ входит. Она измерена и показывается, но
    # низкая цена метра — это выгодно, а не «мимо профиля»: штрафовать за неё
    # значит понижать балл ровно за то, ради чего на торги и ходят. Полосой она
    # остаётся справочной — сравнить вход с тем, по чему покупали раньше.
    checks = [(LAND, land), (BUILDING, building), (PRICE, price)]
    scored: list[float] = []
    misses: list[str] = []
    unknown: list[str] = []
    for band, value in checks:
        if value is None or value <= 0:
            # Неизмеренное — не «плохо». Лот без опубликованной цены не хуже
            # лота с плохой ценой, он просто неизвестен, и так и написано.
            unknown.append(band.name)
            continue
        share, why = _place(value, band)
        scored.append(share)
        if why:
            misses.append(why)
    if not scored:
        return {"fit": None, "matched": 0, "measured": 0, "misses": [],
                "unknown": unknown, "source": BENCHMARK_SOURCE,
                "note": "сравнивать не с чем: у лота нет ни площади, ни цены"}
    fit = sum(scored) / len(scored)
    return {
        "per_sqm": per_sqm,
        "per_sqm_median": PER_SQM.median,
        "fit": round(fit, 3),
        "matched": sum(1 for x in scored if x >= 0.7),
        "measured": len(scored),
        "misses": misses,
        "unknown": unknown,
        "source": BENCHMARK_SOURCE,
        "note": "",
    }


def _number(value: Any) -> float | None:
    try:
        got = float(value)
    except (TypeError, ValueError):
        return None
    return got if got > 0 else None
