"""Словарь терминов — единственный владелец подписей величин.

Подпись величины живёт здесь, а страница, PDF, тизер, книга Excel, Telegram и
Платон её читают. Одна величина в пяти местах называлась «строительным
объёмом», хотя это сумма площадей в м²; строительный объём в отрасли — объём
здания в м³ по наружному обмеру (надземная и подземная части). Переименование
одной строкой здесь — и ни одна поверхность не отстаёт.

Ключи API (`construction_volume_sqm`, `core_total_gns`, `gns`) НЕ меняются:
словарь владеет словами, а не схемой. Полная таблица «наша подпись → что
считается → отраслевой термин» — `docs/glossary.md`.
"""
from __future__ import annotations

from typing import NamedTuple


class Term(NamedTuple):
    key: str
    name: str            # именительный, с заглавной: подпись строки/колонки
    full: str            # полная подпись с составом и единицей
    genitive: str        # родительный, строчный: «тыс. ₽/м² …»
    prepositional: str   # предложный, строчный: «в …»
    unit: str
    formula: str         # что на самом деле считается
    # Подписи, которые этой величине давать нельзя: тест ищет их на
    # отрисованной странице, в PDF и в книге.
    forbidden: tuple[str, ...] = ()

    def lower(self) -> str:
        return self.name[:1].lower() + self.name[1:]

    def with_unit(self) -> str:
        return f"{self.name}, {self.unit}"


# Решение владельца (29.09.2026): «Суммарная площадь в ГНС (СПП + подземная)».
# СПП по ГлавАПУ — только наземные этажи, поэтому сумму с подземной частью
# СПП не зовём; «общая площадь» тоже занята — у нас и у ГлавАПУ это НП.
_FORBIDDEN = ("Строительный объём", "строительный объём", "строительного объёма",
              "строительном объёме", "Строит. объём", "строит. объём",
              "строит. объёма")

# Весь проект: Σ ГНС всех строк ТЭП + подземные гаражи объектов
# (`construction_volume_sqm`).
TOTAL_AREA = Term(
    key="total_area",
    name="Суммарная площадь в ГНС",
    full="Суммарная площадь в ГНС (СПП + подземная), м²",
    genitive="суммарной площади в ГНС",
    prepositional="суммарной площади в ГНС",
    unit="м²",
    formula="Σ ГНС всех строк ТЭП (наземная) + подземная часть (паркинг, кладовые, гаражи объектов)",
    forbidden=_FORBIDDEN,
)

# Только жилые дома (МКД): квартиры + коммерция 1 этажа + подземный паркинг +
# кладовые (`core_total_gns`). На ней считаются общепроектные статьи — ИРД,
# П, РД, подготовка, сети, сдача, содержание — и «строительство на м²».
# С объектами и соцобъектами она меньше суммы проекта, поэтому имя своё.
CORE_TOTAL_AREA = Term(
    key="core_total_area",
    name="Суммарная площадь МКД в ГНС",
    full="Суммарная площадь МКД в ГНС (СПП + подземная), м²",
    genitive="суммарной площади МКД в ГНС",
    prepositional="суммарной площади МКД в ГНС",
    unit="м²",
    formula="ГНС квартир + ГНС коммерции 1 этажа + подземный паркинг + кладовые",
)

# Базы удельных показателей (решение владельца 29.09.2026, ревизия книги,
# решение 4): каждый удельный делится на свою базу и подписывается ею. Какой
# строке какая база — решает движок (`UNIT_ECONOMICS_ROWS`, `capex_unit_base`);
# здесь — только слова.

# Продаваемая площадь проекта (`monetizable_saleable_sqm`): то, что реально
# продаётся метрами. База выручки, цены, EBITDA и прибыли.
SALEABLE_AREA = Term(
    key="saleable_area",
    name="Продаваемая площадь",
    full="Продаваемая площадь (квартиры, коммерция, объекты на продажу метрами), м²",
    genitive="продаваемой площади",
    prepositional="продаваемой площади",
    unit="м²",
    formula="продаваемая площадь квартир, коммерции 1 этажа и объектов, продаваемых метрами",
)

# Наземная ГНС жилых домов (`core_above_gns`): квартиры + коммерция 1 этажа.
# На неё начислено СМР наземной части, на неё же оно и делится.
CORE_ABOVE_AREA = Term(
    key="core_above_area",
    name="Наземная ГНС МКД",
    full="Наземная ГНС МКД (квартиры и коммерция 1 этажа), м²",
    genitive="наземной ГНС МКД",
    prepositional="наземной ГНС МКД",
    unit="м²",
    formula="ГНС квартир + ГНС коммерции 1 этажа",
)

# Подземная площадь жилых домов (`core_under_gns`): паркинг + кладовые.
# База СМР подземной части.
CORE_UNDER_AREA = Term(
    key="core_under_area",
    name="Подземная площадь МКД",
    full="Подземная площадь МКД (паркинг и кладовые), м²",
    genitive="подземной площади МКД",
    prepositional="подземной площади МКД",
    unit="м²",
    formula="ГНС подземного паркинга + ГНС кладовых",
)

# Площади отдельно стоящих объектов: ГНС зданий + их подземные гаражи
# (`objects_total_area`). База статей проекта — ИРД, П, РД, подготовка, сети,
# сдача, содержание — у чисто нежилого проекта, где ставка объекта — только
# СМР здания (решение владельца 06.10.2026, `object_rate_is_turnkey`).
OBJECTS_TOTAL_AREA = Term(
    key="objects_total_area",
    name="Суммарная площадь объектов в ГНС",
    full="Суммарная площадь объектов в ГНС (здания + их подземные гаражи), м²",
    genitive="суммарной площади объектов в ГНС",
    prepositional="суммарной площади объектов в ГНС",
    unit="м²",
    formula="Σ ГНС зданий включённых объектов + их подземные гаражи",
)

TERMS: dict[str, Term] = {term.key: term for term in (
    TOTAL_AREA, CORE_TOTAL_AREA, SALEABLE_AREA, CORE_ABOVE_AREA, CORE_UNDER_AREA,
    OBJECTS_TOTAL_AREA)}


# База удельного у статьи CAPEX: СМР — на ту часть, на которую начислено,
# прочее — на суммарную площадь в ГНС. Это не слово, а выбор, но его читают
# двое — движок (`capex_unit_base`) и Дашборд книги (`v4_dashboard`), — и
# второй копии быть не должно.
CAPEX_UNIT_BASE: dict[str, str] = {"main_above": CORE_ABOVE_AREA.key,
                                   "main_under": CORE_UNDER_AREA.key}


def capex_unit_base(key: str) -> str:
    """База удельного статьи CAPEX по её ключу."""
    return CAPEX_UNIT_BASE.get(str(key), TOTAL_AREA.key)


def unit_label(key: str) -> str:
    """Подпись удельного по ключу базы: «тыс. ₽/м² продаваемой площади»."""
    return f"тыс. ₽/м² {TERMS[key].genitive}"


def page_terms() -> dict[str, dict[str, str]]:
    """Словарь для страницы: те же слова, что у PDF и книги."""
    return {key: {"name": t.name, "lower": t.lower(), "full": t.full,
                  "genitive": t.genitive, "prepositional": t.prepositional,
                  "unit": t.unit, "with_unit": t.with_unit()}
            for key, t in TERMS.items()}


def forbidden_labels() -> tuple[str, ...]:
    return tuple(label for t in TERMS.values() for label in t.forbidden)
