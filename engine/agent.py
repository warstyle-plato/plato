def _agent_client_id(request: Request) -> str:
    forwarded = request.headers.get("x-forwarded-for", "")
    if forwarded:
        return forwarded.split(",")[0].strip()[:80]
    if request.client:
        return str(request.client.host)[:80]
    return "unknown"


def _agent_rate_limit(request: Request) -> None:
    now = time.time()
