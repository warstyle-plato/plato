    client_id = _agent_client_id(request)
    global _AGENT_GLOBAL_BUCKET
    _AGENT_GLOBAL_BUCKET = [t for t in _AGENT_GLOBAL_BUCKET if t >= cutoff]
    bucket = [t for t in _AGENT_RATE_BUCKET.get(client_id, []) if t >= cutoff]
