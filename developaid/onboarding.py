def onboarding_payload() -> dict[str, object]:
    """Return a transport-neutral onboarding payload for web and Telegram."""
    return {
        "title": "Как пользоваться DevelopAid",
        "subtitle": "Первый расчёт за несколько минут",
        "steps": ONBOARDING_STEPS,
        "actions": {
            "primary": "Начать расчёт",
            "secondary": "Пропустить",
            "help": "Как пользоваться",
        },
    }


def telegram_onboarding_text() -> str:
    """Compact onboarding suitable for /start or a persistent help button."""
    lines = ["Как пользоваться DevelopAid"]
    for index, step in enumerate(ONBOARDING_STEPS, start=1):
        lines.append(f"\n{index}. {step['title']}\n{step['text']}")
    return "\n".join(lines)
